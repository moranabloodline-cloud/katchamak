import assert from 'node:assert/strict';
import {compareLibraryProjects,groupLibraryProjects} from '../src/lib/kachamak/library-order.ts';
import {newNovel} from '../src/lib/kachamak/seed.ts';
const project=(title,author,series,index,day)=>({...newNovel(title,author),series,seriesIndex:index,updatedAt:new Date(2026,10,day,12).getTime()});
const projects=[project('Second','Zed','Saga','Book 10',15),project('First','Ada','Saga','Book 2',16),project('Alone','Ada',undefined,undefined,16)];
const before=JSON.stringify(projects);
const titles=sort=>[...projects].sort((a,b)=>compareLibraryProjects(a,b,sort)).map(n=>n.title);
assert.deepEqual(titles('title'),['Alone','First','Second']);
assert.deepEqual(titles('series'),['First','Second','Alone'],'Series sorts natural book indices and puts unassigned books last');
assert.deepEqual(titles('author'),['Alone','First','Second']);
assert.deepEqual(titles('updated'),['Alone','First','Second']);
assert.deepEqual(groupLibraryProjects(projects,'series').map(([label,items])=>[label,items.map(n=>n.title)]),[['Saga',['Second','First']],['No series',['Alone']]]);
assert.deepEqual(groupLibraryProjects(projects,'author').map(([label,items])=>[label,items.length]),[['Ada',2],['Zed',1]]);
assert.deepEqual(groupLibraryProjects(projects,'date').map(([label,items])=>[label,items.length]),[['Nov 16, 2026',2],['Nov 15, 2026',1]]);
assert.deepEqual(groupLibraryProjects(projects,'none'),[['',projects]]);
assert.equal(JSON.stringify(projects),before,'Sorting/grouping do not rewrite project metadata');
const {useLibraryPreferences}=await import('../src/lib/kachamak/library-preferences.ts');
const previous={sort:'created',group:'author',selectedCollection:'books',expanded:['books'],sidebarWidth:320,coverZoom:120,layout:'list'};
const options=useLibraryPreferences.persist.getOptions();assert.equal(options.version,2);
assert.deepEqual(await options.migrate(previous,1),previous,'Migration retains legacy choices, location and layout');
console.log('Library order passed: natural series order, names, authors, dates, all groups, missing series, no mutation and preference migration.');
