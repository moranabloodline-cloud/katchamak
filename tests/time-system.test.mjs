import assert from 'node:assert/strict';
import {GREGORIAN,validCalendar,eraYear,absoluteYear,formatDate,formatCalendarDate,dateToMinute,calendarCells,moonPhase} from '../src/lib/kachamak/story-calendar.ts';
import {useKachamak,isUsableBackup} from '../src/lib/kachamak/store.ts';
import {newNovel} from '../src/lib/kachamak/seed.ts';
import {validCloudLibrary} from '../scripts/cloud-library-runtime.mjs';
const c=structuredClone(GREGORIAN);
c.eraFullName='Common Era';c.beforeEraFullName='Before Common Era';
c.eras=[{id:'rebirth',name:'Age of Rebirth',abbreviation:'AR',startYear:100,color:'#f0883e'}];
c.moons=[{id:'luna',name:'Luna',period:42524.0463,offset:15238,color:'#a371f7'}];
c.dateFormat='MMMM D^, YYYY E';c.timeFormat='12h';
assert.ok(validCalendar(c));
for(const zero of [false,true])for(const year of [-100,-1,0,1,2,99,100,101,9999]){const e=eraYear({...c,yearZero:zero},year);assert.equal(absoluteYear({...c,yearZero:zero},e.year,e.key),year,'Era conversion is reversible across boundaries');}
assert.equal(eraYear(c,100).year,1);assert.equal(eraYear(c,99).abbreviation,'CE');assert.equal(eraYear(c,0).abbreviation,'BCE');
const tick=dateToMinute(c,{year:100,month:0,day:1,hour:13,minute:5});
assert.equal(formatDate(c,tick,'time'),'January 1st, 1 AR · 1:05 PM');
assert.equal(formatCalendarDate(c,tick,'DDDD [year] YYYY [era] EE'),'Friday year 1 era Age of Rebirth');
assert.equal(formatCalendarDate(c,0,'D^'),'1st');
for(const day of [11,12,13,21,22,23,31])assert.equal(formatCalendarDate(c,(day-1)*1440,'D^'),`${day}${day<20?'th':day===21||day===31?'st':day===22?'nd':'rd'}`);
const feb=dateToMinute(c,{year:1,month:1,day:1,hour:0,minute:0});
assert.notEqual(calendarCells(c,feb).findIndex(Boolean),0);
assert.equal(calendarCells({...c,resetWeekdaysEachMonth:true},feb).findIndex(Boolean),0);
assert.equal(formatCalendarDate({...c,resetWeekdaysEachMonth:true},feb,'DDDD'),'Monday');
assert.equal(moonPhase(c.moons[0],15238),0);
assert.ok(Math.abs(moonPhase(c.moons[0],15238-42524.0463/2)-.5)<1e-10);
for(const patch of [{yearZero:'yes'},{resetWeekdaysEachMonth:1},{timeFormat:'25h'},{dateFormat:''},{range:{start:10,end:0}},{eras:[...c.eras,{...c.eras[0],startYear:90}]},{moons:[{...c.moons[0],period:0}]},{moons:[{...c.moons[0],period:Infinity}]},{moons:[{...c.moons[0],color:'red'}]}])assert.equal(validCalendar({...c,...patch}),false);
c.range={start:0,end:tick};assert.ok(validCalendar(c));
const novel=newNovel('Time system roundtrip','QA');novel.timeline={rootId:null,detail:'synopsis',compact:false,calendar:c,display:'chronicle'};
assert.ok(isUsableBackup(novel));assert.ok(validCloudLibrary({novels:[novel],collections:[]}));
assert.deepEqual(JSON.parse(JSON.stringify(novel)).timeline.calendar,c);
const stored={...useKachamak.getInitialState(),novels:[novel]};
useKachamak.persist.setOptions({storage:{getItem:()=>({state:stored,version:10}),setItem(){},removeItem(){}}});
await useKachamak.persist.rehydrate();assert.deepEqual(useKachamak.getState().novels,[novel],'v10 migration must preserve every note, event and calendar field');
assert.equal(useKachamak.persist.getOptions().version,31);
assert.equal(validCalendar({...c,eras:[{...c.eras[0],color:'orange'}]}),false,'Era colours must use safe hex values');
assert.equal(validCloudLibrary({novels:[{...novel,timeline:{...novel.timeline,calendar:{...c,eras:[{...c.eras[0],color:'orange'}]}}}],collections:[]}),false,'The server rejects malformed era colours');
console.log('Time system passed: eras/year zero, date tokens/escaping/ordinals, 12-hour time, weekday reset, fractional lunar cycles, invalid inputs, cloud/backup roundtrip and v10 migration.');
