const { chromium } = require(process.cwd() + '/.qa-runtime/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const sections = { binder: [], codex: [], planning: [], research: [], templates: [], prompts: [] };
const project = (id, title) => ({ id, title, author: 'Test author', cover: { bg: '#333', icon: '' }, sections: structuredClone(sections), trash: [], statuses: [], labels: [], createdAt: 1, updatedAt: 2 });
(async () => {
  fs.mkdirSync('qa-results', { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(({ novels }) => {
    if (localStorage.getItem('qa-seeded')) return;
    localStorage.setItem('kachamak-store-v1', JSON.stringify({ version: 6, state: { novels, activeNovelId: null, view: 'write' } }));
    localStorage.setItem('kachamak-collections-v1', JSON.stringify({ version: 1, state: { collections: [{ id: 'legacy', name: 'Existing collection', projectIds: ['alpha'] }] } }));
    localStorage.setItem('qa-seeded', 'yes');
  }, { novels: [project('alpha', 'Alpha'), project('beta', 'Beta')] });
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('kachamak-collections-v1')).state);
  const contents = page.locator('[aria-label="Library contents"]');
  const tree = page.getByRole('navigation', { name: 'Library hierarchy' });
  const root = () => tree.getByRole('button', { name: /^Library/ }).click();
  const treeFolder = (name) => tree.locator('[draggable="true"]').filter({ has: page.getByRole('button', { name, exact: true }) }).first();
  async function addFolder(name) {
    await page.getByRole('button', { name: 'Collection', exact: true }).click();
    await page.getByLabel('Name', { exact: true }).fill(name);
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
  }
  await page.goto('http://127.0.0.1:4173');
  await tree.waitFor();
  assert.equal(await page.locator('img[src="/dashboard-banner.png"]').count(), 0);
  assert.equal(await page.getByRole('main', { name: 'Project library' }).count(), 1);
  await contents.getByRole('button', { name: 'Open Beta', exact: true }).waitFor();
  await tree.getByRole('button', { name: 'Existing collection', exact: true }).click();
  await contents.getByRole('button', { name: 'Open Alpha', exact: true }).waitFor();
  await root(); await addFolder('Top');
  let s = await state(); const top = s.collections.find((c) => c.name === 'Top').id;
  assert.equal(s.collections.find((c) => c.id === top).parentId, null);
  await addFolder('Child'); await addFolder('Grandchild');
  s = await state(); const child = s.collections.find((c) => c.name === 'Child').id; const grand = s.collections.find((c) => c.name === 'Grandchild').id;
  assert.equal(s.collections.find((c) => c.id === grand).parentId, child);
  await root();
  await contents.getByRole('button', { name: 'Open Beta', exact: true }).locator('..').dragTo(treeFolder('Child'));
  await page.waitForFunction(({ child }) => JSON.parse(localStorage.getItem('kachamak-collections-v1')).state.collections.find((c) => c.id === child).projectIds.includes('beta'), { child });
  await tree.getByRole('button', { name: 'Child', exact: true }).click();
  await contents.getByRole('button', { name: 'Open Beta', exact: true }).waitFor();
  const grandTile = contents.locator('[draggable="true"]').filter({ has: page.getByRole('button', { name: /^Grandchild/ }) }).first();
  await contents.getByRole('button', { name: 'Open Beta', exact: true }).locator('..').dragTo(grandTile);
  await page.waitForFunction(({ grand }) => JSON.parse(localStorage.getItem('kachamak-collections-v1')).state.collections.find((c) => c.id === grand).projectIds.includes('beta'), { grand });
  await treeFolder('Grandchild').dragTo(treeFolder('Existing collection'));
  await page.waitForFunction(({ grand }) => JSON.parse(localStorage.getItem('kachamak-collections-v1')).state.collections.find((c) => c.id === grand).parentId === 'legacy', { grand });
  await tree.getByRole('button', { name: 'Existing collection', exact: true }).click();
  await contents.getByRole('button', { name: /^Grandchild/ }).waitFor();
  const beforeCycle = JSON.stringify((await state()).collections);
  await treeFolder('Existing collection').dragTo(treeFolder('Grandchild'));
  assert.equal(JSON.stringify((await state()).collections), beforeCycle, 'cyclic native drop is rejected');
  await tree.getByRole('button', { name: 'Grandchild', exact: true }).click();
  await contents.getByRole('button', { name: 'Open Beta', exact: true }).waitFor();
  const previousSize = (await state()).coverSize;
  const headerHeight = await page.locator('header').evaluate((el) => el.getBoundingClientRect().height);
  await contents.hover(); await page.keyboard.down('Control'); await page.mouse.wheel(0, -120); await page.keyboard.up('Control');
  await page.waitForFunction((previousSize) => JSON.parse(localStorage.getItem('kachamak-collections-v1')).state.coverSize > previousSize, previousSize);
  assert.equal(await page.locator('header').evaluate((el) => el.getBoundingClientRect().height), headerHeight, 'cover zoom does not resize the app shell');
  const handle = page.getByRole('separator', { name: 'Resize collections panel' });
  const box = await handle.boundingBox(); await page.mouse.move(box.x, box.y + 100); await page.mouse.down(); await page.mouse.move(340, box.y + 100, { steps: 8 }); await page.mouse.up();
  assert.ok((await state()).sidebarWidth >= 330);
  await page.getByRole('button', { name: 'List view' }).click();
  await contents.getByRole('button', { name: 'Open Beta', exact: true }).waitFor();
  assert.equal((await state()).layout, 'list');
  const saved = await state(); await page.reload(); await tree.waitFor();
  assert.equal((await state()).coverSize, saved.coverSize); assert.equal((await state()).sidebarWidth, saved.sidebarWidth); assert.equal((await state()).layout, 'list');
  assert.deepEqual((await state()).collections, saved.collections);
  await tree.getByRole('button', { name: 'Grandchild', exact: true }).click();
  await page.getByRole('button', { name: 'Options for Beta', exact: true }).last().click();
  await page.getByRole('menuitem', { name: 'Set cover image', exact: true }).click();
  await page.locator('input[aria-label="Project cover image"]').setInputFiles({ name: 'cover.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aacsAAAAASUVORK5CYII=', 'base64') });
  await page.waitForFunction(() => !!JSON.parse(localStorage.getItem('kachamak-collections-v1')).state.projectMeta.beta?.coverUrl);
  await contents.locator('img[alt="Beta cover"]').waitFor();
  // More projects exercise independent scrolling and a responsive book-cover grid.
  await page.evaluate(({ extras }) => {
    const app = JSON.parse(localStorage.getItem('kachamak-store-v1')); app.state.novels.push(...extras); localStorage.setItem('kachamak-store-v1', JSON.stringify(app));
  }, { extras: Array.from({ length: 45 }, (_, i) => project('extra-' + i, 'Test book ' + (i + 1))) });
  await page.reload(); await tree.waitFor(); await root(); await page.getByRole('button', { name: 'Grid view' }).click();
  await contents.getByRole('button', { name: 'Open Test book 1', exact: true }).waitFor();
  const left = await tree.evaluate((el) => ({ top: el.scrollTop, h: el.scrollHeight, client: el.clientHeight }));
  assert.ok(left.h > left.client);
  await contents.evaluate((el) => { el.scrollTop = 250; });
  assert.equal(await tree.evaluate((el) => el.scrollTop), left.top);
  assert.ok(await contents.evaluate((el) => el.scrollTop > 0));
  await contents.evaluate((el) => { el.scrollTop = 0; });
  await page.screenshot({ path: 'qa-results/library-1440.png', fullPage: true });
  for (const width of [1280, 1920]) {
    await page.setViewportSize({ width, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no horizontal page overflow');
    await page.screenshot({ path: 'qa-results/library-' + width + '.png', fullPage: true });
  }
  await tree.getByRole('button', { name: 'Grandchild', exact: true }).click();
  await contents.getByRole('button', { name: 'Open Beta', exact: true }).click();
  await page.getByRole('navigation', { name: 'Workspace sections' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Binder', exact: true }).count(), 1);
  assert.deepEqual(errors, [], 'no browser runtime errors');
  fs.writeFileSync('qa-results/results.json', JSON.stringify({ passed: true, tested: ['migration', 'nested creation', 'native drag and drop in both panels', 'cycles', 'cover zoom', 'resize', 'list/grid', 'reload', 'cover upload', 'independent scroll', 'desktop widths', 'workspace'] }, null, 2));
  await browser.close(); console.log('Dashboard browser checks passed.');
})().catch((error) => { console.error(error); process.exit(1); });
