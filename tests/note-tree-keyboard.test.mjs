import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const dom = new Window({ url: 'https://test.local' });
for (const key of ['window','document','HTMLElement','Element','Node','MutationObserver','getComputedStyle','navigator','requestAnimationFrame','cancelAnimationFrame']) Object.defineProperty(globalThis,key,{configurable:true,value:typeof dom[key]==='function'&&!/^[A-Z]/.test(key)?dom[key].bind(dom):dom[key]});
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const React = await import('react');
const {createRoot} = await import('react-dom/client');
const {useKachamak} = await import('../src/lib/kachamak/store.ts');
const {findNode} = await import('../src/lib/kachamak/utils.ts');
const {NoteTree} = await import('../src/components/kachamak/NoteTree.tsx');
const container=document.createElement('div');document.body.append(container);const root=createRoot(container);
useKachamak.getState().createNovel('Keyboard tree','Tester');
const actions=useKachamak.getState();
const act=actions.addNode('binder',null,'doc','Act One');
const ch9=actions.addNode('binder',act,'doc','Chapter 9');
const ch10=actions.addNode('binder',act,'doc','Chapter 10 - Flatline');
const child=actions.addNode('binder',ch10,'doc','A hidden child');
const ch11=actions.addNode('binder',act,'doc','Chapter 11');
const hidden=actions.addNode('binder',act,'doc','Hidden note');
const next=actions.addNode('binder',null,'doc','Act Two');
actions.updateNode('binder',ch10,{collapsed:true});actions.updateNode('binder',hidden,{hidden:true});actions.setRenamingNode(null);
useKachamak.setState({view:'split',activePane:'a',paneBId:next,selectedNodeId:ch10,paneAId:ch10});
await React.act(async()=>root.render(React.createElement(NoteTree,{section:'binder'})));
const row=id=>[...container.querySelectorAll('[role="treeitem"]')].find(el=>el.dataset.noteId===id);
const key=async(name,target=document.activeElement,options={})=>{await React.act(async()=>target.dispatchEvent(new dom.KeyboardEvent('keydown',{key:name,bubbles:true,cancelable:true,...options})));};
await React.act(async()=>row(ch10).click());assert.equal(document.activeElement,row(ch10));
await key('ArrowDown');assert.equal(useKachamak.getState().selectedNodeId,ch11,'Down skips collapsed descendants');assert.equal(document.activeElement,row(ch11));
await key('ArrowDown');assert.equal(useKachamak.getState().selectedNodeId,next,'Hidden notes are skipped');
await key('ArrowDown');assert.equal(useKachamak.getState().selectedNodeId,next,'End does not wrap');
await key('ArrowUp');assert.equal(useKachamak.getState().selectedNodeId,ch11);
await key('ArrowUp');assert.equal(useKachamak.getState().selectedNodeId,ch10);
await key('ArrowRight');assert.equal(row(ch10).getAttribute('aria-expanded'),'true');assert.equal(useKachamak.getState().selectedNodeId,ch10);
await key('ArrowRight');assert.equal(useKachamak.getState().selectedNodeId,child);
await key('ArrowLeft');assert.equal(useKachamak.getState().selectedNodeId,ch10);
await key('ArrowLeft');assert.equal(row(ch10).getAttribute('aria-expanded'),'false');
await key('Home');assert.equal(useKachamak.getState().selectedNodeId,act);
await key('ArrowUp');assert.equal(useKachamak.getState().selectedNodeId,act,'Start does not wrap');
await key('End');assert.equal(useKachamak.getState().selectedNodeId,next);
assert.equal(useKachamak.getState().paneBId,next,'Other Split pane stays unchanged');assert.equal(useKachamak.getState().view,'split');
await React.act(async()=>{actions.select(ch10);actions.setRenamingNode(ch10);});
const input=row(ch10).querySelector('input');input.focus();await key('ArrowDown',input);assert.equal(useKachamak.getState().selectedNodeId,ch10,'Rename arrows do not navigate');
await key('Delete',input);assert.ok(findNode(useKachamak.getState().novels[0].sections.binder,ch10),'Rename Delete must not remove the note');
await React.act(async()=>actions.setRenamingNode(null));
row(ch10).focus();await key('ArrowDown',row(ch10),{ctrlKey:true});assert.equal(useKachamak.getState().selectedNodeId,ch10,'Modified arrows keep their own meaning');
await React.act(async()=>{actions.setTreeScope('top');root.render(React.createElement(NoteTree,{section:'binder'}));});
row(act).focus();await key('ArrowDown');assert.equal(useKachamak.getState().selectedNodeId,next,'Keyboard follows the displayed scope');
await React.act(async()=>{actions.setTreeScope('all');root.render(React.createElement(NoteTree,{section:'binder',rootId:act}));});
row(ch11).focus();await key('ArrowDown');assert.equal(document.activeElement,row(ch11),'A folder tab cannot navigate outside its subtree');
await React.act(async()=>root.unmount());
console.log('Tree keyboard passed: clicked Chapter 10, visible Up/Down order, collapsed/hidden notes, Left/Right, Home/End, boundaries, focus, rename safety, scopes and Split isolation.');
