import assert from 'node:assert/strict';
import {unifiedCanvas,inFixedRow,canvasParts,worldRows} from '../src/lib/kachamak/canvas-layout.ts';
import {changeHomepage,validHomepage} from '../src/lib/kachamak/homepage.ts';
import {useKachamak} from '../src/lib/kachamak/store.ts';
import {newNovel} from '../src/lib/kachamak/seed.ts';
import {isReadableProject} from '../src/lib/kachamak/project-validation.ts';

const item=(id,layout,extra={})=>({id,layout,title:id,text:'',width:'standard',...extra});
const row=item('r','row',{width:'full',columns:6});
const source={locked:false,blocks:[item('banner','banner',{width:'full'}),item('m','card'),item('n','card'),row,
  item('scene','note',{cell:{rowId:'r',column:0}}),item('end','text',{cell:{rowId:'r',column:5}})]};
const old=structuredClone(source);
let page=unifiedCanvas(source);
assert.deepEqual(old,source);assert.deepEqual(page,unifiedCanvas(source));assert.equal(unifiedCanvas(page),page);
assert.ok(validHomepage(page));assert.ok(page.blocks.filter(b=>b.layout!=='row').every(b=>!!b.cell));
assert.equal(page.blocks.find(b=>b.id==='m').cell.rowId,page.blocks.find(b=>b.id==='n').cell.rowId);
const apply=action=>{const next=changeHomepage(page,action);assert.ok(next);assert.ok(validHomepage(next));page=next;};
apply({type:'into',id:'scene',cell:{rowId:'r',column:5}});
apply({type:'move',id:'scene',offset:-1});
assert.deepEqual(page.blocks.filter(b=>b.cell?.column===5).map(b=>b.id),['scene','end']);
for(const action of [{type:'move',id:'r',offset:-1},{type:'boardMove',id:'r',at:{x:0,y:0}},
 {type:'boardMove',id:'end',at:{x:0,y:0}},{type:'place',id:'end',targetId:'r',side:'after'},
 {type:'into',id:'end',cell:page.blocks.find(b=>b.id==='m').cell}])assert.equal(changeHomepage(page,action),null);
apply({type:'edit',original:row,block:{...row,columns:2}});
assert.ok(page.blocks.filter(b=>b.cell?.rowId==='r').every(b=>b.cell.column===1));
const fixed=page.blocks.filter(inFixedRow);
for(const [n,id] of ['x','y'].entries())apply({type:'add',block:item(id,'note',{at:{x:n*300,y:0}})});
apply({type:'add',block:item('edge','line',{edge:{from:'x',to:'y'}})});
apply({type:'boardMove',id:'x',at:{x:-20,y:87}});
assert.deepEqual(page.blocks.filter(inFixedRow),fixed);
assert.equal(changeHomepage(page,{type:'into',id:'x',cell:{rowId:'r',column:0}}),null);
assert.ok(validHomepage(changeHomepage(page,{type:'add',block:item('linked','line',{edge:{from:'x',to:'end'}})})));
assert.equal(changeHomepage(page,{type:'add',block:item('invalid','line',{edge:{from:'x',to:'r'}})}),null);
const originalX=page.blocks.find(b=>b.id==='x');
const cell={rowId:'r',column:0};
const dock={type:'dockCards',ids:['x'],cell};
const release={type:'releaseCards',ids:['x'],cell,at:{x:-40,y:310}};
assert.equal(changeHomepage({...page,locked:true},dock),null);
assert.equal(changeHomepage(page,{...dock,cell:{...cell,column:9}}),null);
apply(dock);
assert.equal(page.blocks.filter(b=>b.id==='x').length,1);
assert.deepEqual(page.blocks.find(b=>b.id==='x'),{...originalX,at:undefined,columnId:undefined,cell});
assert.ok(!canvasParts(page.blocks).free.some(b=>b.id==='edge'));
assert.equal(canvasParts(page.blocks).parked[0].id,'edge');
apply({type:'boardMove',id:'y',at:{x:500,y:50}});
assert.equal(changeHomepage(page,dock),null);
assert.equal(changeHomepage(page,{type:'boardMove',id:'x',at:{x:4,y:4}}),null);
assert.equal(changeHomepage(page,{...release,cell:{...cell,column:1}}),null);
assert.equal(changeHomepage(page,{...release,at:{x:NaN,y:0}}),null);
const removed=changeHomepage(page,{type:'remove',original:page.blocks.find(b=>b.id==='x')});
assert.ok(validHomepage(removed));assert.ok(!removed.blocks.some(b=>b.id==='edge'));
const removedOther=changeHomepage(page,{type:'removeBoardItem',original:page.blocks.find(b=>b.id==='y'),positions:{}});
assert.ok(validHomepage(removedOther));assert.ok(!removedOther.blocks.some(b=>b.id==='edge'));
const held=JSON.parse(JSON.stringify(page));assert.ok(validHomepage(held));
const heldBook=newNovel('Held','Test');heldBook.homepage=held;assert.ok(isReadableProject(heldBook));
const dangling=structuredClone(held);dangling.blocks.find(b=>b.id==='edge').edge.from='absent';
assert.equal(validHomepage(dangling),false);
assert.equal(changeHomepage({...page,locked:true},release),null);
apply(release);
assert.equal(changeHomepage(page,release),null);
assert.equal(canvasParts(page.blocks).free.filter(b=>b.id==='edge').length,1);
assert.deepEqual(page.blocks.find(b=>b.id==='x').at,release.at);
// Creation and click order differ from visual order. Keep both internal and external line IDs.
const groupRow=item('row','row',{width:'full',columns:2});
const lane={rowId:'row',column:1};
const link=(id,from,to)=>item(id,'line',{edge:{from,to}});
const original={mode:'canvas',locked:false,blocks:[
  groupRow,item('already','note',{cell:lane}),item('right','image',{at:{x:350,y:4},image:'gallery:old'}),
  item('next','note',{at:{x:0,y:140}}),item('left','note',{at:{x:20,y:12}}),
  item('other','note',{at:{x:800,y:12}}),link('inside','left','right'),link('outside','next','other')]};
// A new palette card is saved in its column at the captured sibling, in one operation.
const insert={type:'add',block:item('fresh','note',{cell:lane}),before:'already'};
const inserted=changeHomepage(original,insert);
assert.ok(validHomepage(inserted));
assert.deepEqual(inserted.blocks.filter(b=>b.cell).map(b=>b.id),['fresh','already']);
assert.equal(changeHomepage(inserted,insert),null);
assert.equal(changeHomepage({...original,locked:true},insert),null);
assert.equal(changeHomepage(original,{...insert,block:{...insert.block,cell:{rowId:'row',column:9}}}),null);
for(const anchor of ['moved-away','right']){
  const appended=changeHomepage(original,{...insert,before:anchor});
  assert.deepEqual(appended.blocks.filter(b=>b.cell).map(b=>b.id),['already','fresh']);
}
const ids=['next','right','left'],groupDock={type:'dockCards',ids,cell:lane};
let group=changeHomepage(original,groupDock);assert.ok(validHomepage(group));
const ordered=['left','right','next'];
assert.deepEqual(group.blocks.filter(b=>b.cell).map(b=>b.id),['already',...ordered]);
assert.deepEqual(canvasParts(group.blocks).parked.map(b=>b.id),['inside','outside']);
assert.equal(group.blocks.find(b=>b.id==='right').image,'gallery:old');
assert.equal(group.blocks.length,original.blocks.length);
for(const badIds of [[],['right','absent'],['right','right'],['left','row'],['left','already'],['right','inside']]){
  assert.equal(changeHomepage(original,{...groupDock,ids:badIds}),null);
}
const lockedPeer={...original,blocks:original.blocks.map(b=>b.id==='next'?{...b,positionLocked:true}:b)};
assert.equal(changeHomepage(lockedPeer,groupDock),null);
assert.equal(changeHomepage(group,groupDock),null);
group=JSON.parse(JSON.stringify(group));
const groupRelease={type:'releaseCards',ids:[...ids].reverse(),cell:lane,at:{x:24,y:300}};
assert.equal(changeHomepage(group,{...groupRelease,ids:['right','other']}),null);
assert.equal(changeHomepage({...group,locked:true},groupRelease),null);
const result=changeHomepage(group,groupRelease);assert.ok(validHomepage(result));
assert.deepEqual(result.blocks.filter(b=>ids.includes(b.id)).map(b=>b.id),ordered);
const positions=ordered.map(id=>result.blocks.find(b=>b.id===id).at);
assert.ok(positions.every(p=>p.y===300));assert.ok(positions[0].x<positions[1].x&&positions[1].x<positions[2].x);
assert.deepEqual(canvasParts(result.blocks).free.filter(b=>b.edge),original.blocks.filter(b=>b.edge));
assert.equal(result.blocks.length,original.blocks.length);assert.equal(result.blocks.find(b=>b.id==='right').image,'gallery:old');
assert.equal(changeHomepage(result,groupRelease),null);
const book=newNovel('Canvas','Test');book.homePages=[{...page,id:'c',title:'One canvas',parentId:null}];
useKachamak.setState({novels:[book],activeNovelId:book.id,activeHomePageId:'c'});
assert.ok(useKachamak.getState().convertBoardSelection(book.id,'c',['x','y'],'Linked canvas',[]));
const updated=useKachamak.getState().novels[0];assert.ok(isReadableProject(JSON.parse(JSON.stringify(updated))));
assert.deepEqual(updated.homePages[0].blocks.filter(inFixedRow),fixed);assert.equal(updated.homePages[1].mode,'canvas');
apply({type:'remove',original:page.blocks.find(b=>b.id==='r')});
assert.ok(page.blocks.find(b=>b.id==='end').at);assert.ok(!page.blocks.find(b=>b.id==='end').cell);
assert.ok(validHomepage(JSON.parse(JSON.stringify(page))));
const board={mode:'board',locked:true,blocks:[item('a','note',{at:{x:-22,y:32}})]};
assert.deepEqual(unifiedCanvas(board).blocks,board.blocks);
assert.equal(changeHomepage(unifiedCanvas(board),{type:'add',block:row}),null);
const oldMixed={mode:'canvas',locked:false,blocks:[row,item('loose','note',{at:{x:-2000,y:7}})]};
const migrated=unifiedCanvas(oldMixed);
const legacyBounds=worldRows([row],1160,new Map(),migrated.legacyRowX).get('r');
assert.ok(legacyBounds.x+legacyBounds.w<-2000);
assert.deepEqual(oldMixed.blocks,migrated.blocks);
const newRow=item('world','row',{columns:2,at:{x:400,y:200}});
const below={...row,id:'below',at:{x:400,y:380}};
const heights=new Map([['world',340]]);
const grown=worldRows([newRow,below],1160,heights);
assert.equal(grown.get('world').h,340);assert.equal(grown.get('below').y,556);
const column=item('standing','column',{at:{x:202,y:-610}});
const withColumn=changeHomepage(migrated,{type:'add',block:column});
assert.ok(withColumn);
assert.equal(changeHomepage(withColumn,{type:'boardMove',id:column.id,at:{x:0,y:0}}),null);
assert.equal(changeHomepage(withColumn,{type:'boardSelection',ids:['standing','loose'],command:{kind:'translate',delta:{x:11,y:13}}}),null);
assert.ok(changeHomepage(withColumn,{type:'boardMove',id:'loose',columnId:'standing',at:{x:0,y:0}}));
// Explicit placements may intersect another row. Row contents and other rows keep their positions.
const clicked=item('clicked','row',{columns:2,at:{x:450.5,y:215.25},manualPosition:true});
const rowBook={mode:'canvas',locked:false,blocks:[newRow,below,clicked,item('nested','note',{cell:{rowId:newRow.id,column:1}})]};
const beforeMove=worldRows([newRow,below,clicked],1160,heights);
assert.equal(beforeMove.get('clicked').y,215.25);
const moveRow={type:'moveRow',id:newRow.id,at:{x:-187.5,y:30.75},heights:[...heights]};
const dragged=changeHomepage(rowBook,moveRow);
assert.ok(validHomepage(dragged));assert.deepEqual(dragged.blocks.find(b=>b.id==='nested'),rowBook.blocks[3]);
const afterMove=worldRows(dragged.blocks.filter(b=>b.layout==='row'),1160,heights);
assert.deepEqual(afterMove.get('below'),beforeMove.get('below'));assert.deepEqual(afterMove.get('clicked'),beforeMove.get('clicked'));
assert.deepEqual(dragged.blocks[0].at,moveRow.at);
assert.equal(changeHomepage({...rowBook,locked:true},moveRow),null);
assert.equal(changeHomepage(rowBook,{...moveRow,id:'nested'}),null);
assert.equal(changeHomepage(rowBook,{...moveRow,at:{x:Infinity,y:0}}),null);
const lockedPage={...dragged,locked:true};
const styled=changeHomepage(changeHomepage(lockedPage,{type:'appearance',field:'icon',value:'bookmark'}),{type:'appearance',field:'color',value:'#58a6ff'});
assert.ok(validHomepage(JSON.parse(JSON.stringify(styled))));assert.equal(styled.color,'#58a6ff');assert.equal(styled.icon,'bookmark');
assert.equal(changeHomepage(styled,{type:'appearance',field:'icon',value:''}).color,styled.color);
assert.equal(changeHomepage(styled,{type:'appearance',field:'color',value:'bad'}),null);
const placed=changeHomepage(migrated,{type:'add',block:newRow});
assert.ok(validHomepage(placed));assert.deepEqual(placed.blocks.find(b=>b.id==='world').at,newRow.at);
const removedColumn=changeHomepage(original,{type:'remove',original:groupRow,column:lane.column,positions:{already:{x:700,y:400}}});
assert.ok(validHomepage(removedColumn));assert.deepEqual(removedColumn.blocks.find(b=>b.id==='already').at,{x:700,y:400});
assert.ok(!removedColumn.blocks.find(b=>b.id==='already').cell);
assert.equal(removedColumn.blocks.find(b=>b.id===groupRow.id).columns,1);
assert.ok(useKachamak.getState().deleteHomePage(book.id,'c'));assert.equal(useKachamak.getState().activeHomePageId,'home');
assert.equal(useKachamak.getState().novels[0].homePages.length,0);
console.log('Unified Canvas passed fixed rows, legacy layout, resize, reorder, free movement, connections, release and nested conversion.');
