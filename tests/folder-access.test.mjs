import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const dom = new Window({ url: 'https://katchamak.test/' });
globalThis.window = dom;
const { requestFolder, requestFolderWindow, FOLDER_ACCESS } = await import('../src/lib/kachamak/folder-access.ts');
let pickCount = 0, permissionCount = 0, permission = 'granted';
const handle = { kind: 'directory', name: 'My library', queryPermission: async () => permission, requestPermission: async () => { permissionCount++; return 'granted'; } };
window.showDirectoryPicker = async () => { pickCount++; return handle; };
assert.equal(await requestFolder('owner'), handle);
assert.equal(pickCount, 1);
assert.equal(await requestFolder('owner', handle, false), handle);
assert.equal(permissionCount, 0, 'existing grants are reused');
permission = 'prompt';
assert.equal(await requestFolder('owner', handle, false), handle);
assert.equal(permissionCount, 1);
assert.equal(pickCount, 1, 'renewal does not choose a different root');
permission = 'granted';
let popup, opened, messages;
window.open = url => {
  opened = new URL(url); messages = [];
  popup = { closed: false, close() { this.closed = true; }, postMessage(data, origin) { messages.push({ data, origin }); } };
  return popup;
};
const emit = (data, { origin = window.location.origin, source = popup } = {}) => window.dispatchEvent(new dom.MessageEvent('message', { origin, source, data: { type: FOLDER_ACCESS, requestId: opened.searchParams.get('request'), ...data } }));
const pending = requestFolderWindow('owner', handle, false);
emit({ action: 'ready' }, { origin: 'https://untrusted.test' });
assert.equal(messages.length, 0, 'wrong origin ignored');
emit({ action: 'ready' }, { source: {} });
assert.equal(messages.length, 0, 'unrelated window ignored');
emit({ action: 'ready', requestId: 'wrong' });
assert.equal(messages.length, 0, 'wrong nonce ignored');
emit({ action: 'ready' });
assert.equal(messages[0].data.current, handle);
assert.equal(messages[0].data.accountId, 'owner');
assert.equal(messages[0].origin, window.location.origin);
emit({ action: 'selected', accountId: 'owner', handle });
assert.equal(await pending, handle, 'the real handle is returned, not a memory clone');
assert.equal(messages.at(-1).data.action, 'accepted');
// Some embedded hosts expose the API, but reject it. The ordinary Choose action
// must use the permission window in that case too, not create a virtual library.
window.showDirectoryPicker = async () => { throw new DOMException('Blocked in this context', 'SecurityError'); };
const blocked = requestFolder('owner');
await new Promise(resolve => setTimeout(resolve, 0));
emit({ action: 'ready' });
emit({ action: 'selected', accountId: 'owner', handle });
assert.equal(await blocked, handle);
const mismatch = requestFolderWindow('owner', null, true);
emit({ action: 'selected', accountId: 'other-user', handle });
await assert.rejects(mismatch, /different account/);
assert.equal(popup.closed, true);
const cancelled = requestFolderWindow('owner', null, true);
emit({ action: 'cancel' });
await assert.rejects(cancelled, { name: 'AbortError' });
window.open = () => null;
await assert.rejects(requestFolderWindow('owner', null, true), /Allow the folder connection window/);
delete window.showDirectoryPicker;
await assert.rejects(requestFolder('owner'), /does not provide writable local folders/);
console.log('Folder access: real handle transfer, origin/window/nonce/account checks, cancellation, blocked popup and permission reuse passed.');
