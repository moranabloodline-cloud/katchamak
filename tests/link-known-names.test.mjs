import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
const dom=new JSDOM().window;globalThis.window=dom;globalThis.document=dom.document;globalThis.DOMParser=dom.DOMParser;
const {linkKnownNames}=await import('../src/lib/kachamak/link-known-names.ts');
const {countWords}=await import('../src/lib/kachamak/utils.ts');
const {preparePastedContent}=await import('../src/lib/kachamak/paste-content.ts');
const notes=[{id:'morana',title:'Morrigan',aliases:['Morana']},{id:'ann',title:'Ann'},{id:'cira',title:'Ćira'}];
const input='<p><b>Morana</b> met ĆIRA, not annex. <a href="#note/morana">Morana</a></p><p><br></p><pre>Morana</pre>';
const result=linkKnownNames(input,notes);
assert.equal(countWords(input),countWords(result.html),'Adding inline links must not change word count');
assert.equal(result.count,2);const box=document.createElement('div');box.innerHTML=result.html;
assert.equal(box.querySelector('b a').textContent,'Morana');assert.ok(box.querySelector('p + p br'));assert.equal(box.querySelector('pre').innerHTML,'Morana');assert.equal(box.querySelectorAll('a').length,3);
assert.equal(linkKnownNames(result.html,notes).count,0,'Linking is idempotent');
assert.equal(linkKnownNames('<p>Morana</p>',[...notes,{id:'other',title:'Another',aliases:['Morana']}]).count,0,'Ambiguous names require a manual target');
const pasted=preparePastedContent(result.html,'');assert.ok(pasted.includes('href="#note/morana"'));assert.ok(pasted.includes('data-katchamak-note="morana"'));
console.log('User-triggered name linking passed: formatting, blank paragraphs, Unicode, word boundaries, existing links, ambiguous aliases and paste roundtrip.');
