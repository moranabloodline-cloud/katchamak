import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'https://test.local',pretendToBeVisual:true}).window;
for(const key of ['window','document','HTMLElement','Element','Node','Event','MouseEvent','MutationObserver','navigator','requestAnimationFrame','cancelAnimationFrame'])Object.defineProperty(globalThis,key,{configurable:true,value:key==='window'?dom:typeof dom[key]==='function'&&!/^[A-Z]/.test(key)?dom[key].bind(dom):dom[key]});
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const React=await import('react'),{createRoot}=await import('react-dom/client');
const {DocumentOutline}=await import('../src/components/kachamak/DocumentOutline.tsx');
const root=createRoot(document.body.appendChild(document.createElement('div')));
const html='<h2>Overview</h2><p>Keep this prose.</p><h3><strong>Same name</strong></h3><h3>Same name</h3><h6>Deep heading</h6><h2> </h2>';
const page=(pane,content)=>React.createElement('div',{'data-pane':pane},React.createElement('div',{className:'kachamak-editor',dangerouslySetInnerHTML:{__html:content}}));
const render=(pane='a',scopeKey='one')=>React.createElement(DocumentOutline,{title:'Chapter',pane,scopeKey},page('a',html),page('b','<h1>Other pane</h1>'));
await React.act(async()=>root.render(render()));
const entries=()=>[...document.querySelectorAll('nav[aria-label="Document headings"] button')];
assert.deepEqual(entries().map(x=>x.textContent),['Overview','Same name','Same name','Deep heading']);
assert.ok(parseInt(entries()[1].style.paddingLeft)>parseInt(entries()[0].style.paddingLeft),'Subheadings are indented');
const editor=document.querySelector('[data-pane="a"] .kachamak-editor'),before=editor.innerHTML;
let scrolled=null;dom.HTMLElement.prototype.scrollIntoView=function(){scrolled=this;};
await React.act(async()=>entries()[2].click());
assert.equal(scrolled,editor.querySelectorAll('h3')[1],'Duplicate labels scroll to their own exact occurrence');
assert.equal(editor.innerHTML,before,'Outline navigation never injects IDs or changes the manuscript');
await React.act(async()=>{editor.querySelector('h3').firstChild.textContent='Renamed';});
assert.equal(entries()[1].textContent,'Renamed','Typing inside an inline heading updates immediately');
await React.act(async()=>{editor.querySelectorAll('h3')[1].replaceWith(document.createElement('p'));});
assert.equal(entries().length,3,'Removing heading formatting removes its outline entry');
await React.act(async()=>{const h=document.createElement('h4');h.textContent='New section';editor.append(h);});
assert.equal(entries().at(-1).textContent,'New section');
await React.act(async()=>root.render(render('b')));
assert.deepEqual(entries().map(x=>x.textContent),['Other pane'],'Split uses only the active pane');
await React.act(async()=>document.querySelector('[aria-label="Hide document outline"]').click());
assert.equal(entries().length,0);assert.ok(document.querySelector('[aria-label="Show document outline"]'));
await React.act(async()=>document.querySelector('[aria-label="Show document outline"]').click());
assert.deepEqual(entries().map(x=>x.textContent),['Other pane']);
await React.act(async()=>root.render(React.createElement(DocumentOutline,{title:'Empty',scopeKey:'empty'},page('a','<p>No headings yet</p>'))));
assert.equal(entries().length,0);assert.match(document.querySelector('nav').textContent,/Headings you add/,'Switching notes clears the previous outline');
await React.act(async()=>root.unmount());
console.log('Document outline passed: hierarchy, live edits, exact duplicate target, read-only navigation, pane scope, hide/show and note changes.');
