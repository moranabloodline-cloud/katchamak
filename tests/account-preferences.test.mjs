import assert from 'node:assert/strict';
let accesses = 0;
Object.defineProperty(globalThis, 'localStorage', { configurable: true, get() { accesses++; throw new DOMException('Storage denied', 'SecurityError'); } });
const { useAccountPreferences } = await import('../src/lib/kachamak/account-preferences.ts');
const { useAppearancePreferences } = await import('../src/lib/kachamak/appearance-preferences.ts');
assert.deepEqual(useAccountPreferences.getState(), {displayName:'',photo:null});
useAccountPreferences.setState({displayName:'Cloud Writer',photo:'data:image/png;base64,test'});
assert.equal(useAccountPreferences.getState().displayName,'Cloud Writer');
useAppearancePreferences.setState({theme:'light',interfaceSize:'large'});
assert.deepEqual(useAppearancePreferences.getState(), {theme:'light',interfaceSize:'large'});
assert.equal(accesses, 0, 'Account and appearance hydration never accesses browser storage, even if blocked');
console.log('Account and appearance use account-loaded state without browser storage reads or writes.');
