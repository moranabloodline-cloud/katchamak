import assert from 'node:assert/strict';
import {changeGallery, galleryPath, validGallery} from '../src/lib/kachamak/gallery.ts';
import {validCloudLibrary} from '../src/lib/kachamak/cloud-write-validation.mjs';
import {isReadableProject} from '../src/lib/kachamak/project-validation.ts';
import {newNovel} from '../src/lib/kachamak/seed.ts';

const maps={kind:'folder',id:'maps',parentId:null,name:'Maps'};
const city={kind:'folder',id:'city',parentId:'maps',name:'City'};
const image={kind:'image',id:'map',parentId:'city',name:'Old town.png',image:'data:image/png;base64,aGVsbG8='};
const emptyBook=newNovel('Gallery QA','Synthetic');
assert.ok(isReadableProject(emptyBook));
let entries=changeGallery([],{type:'add',entries:[maps,city,image]});
assert.deepEqual(galleryPath(entries,'city'),[maps,city]);
assert.throws(()=>changeGallery(entries,{type:'move',id:'maps',parentId:'city'}));
assert.throws(()=>changeGallery(entries,{type:'remove',id:'city'}));
assert.throws(()=>changeGallery(entries,{type:'add',entries:[image]}));
assert.equal(validGallery([{...maps,parentId:'missing'}]),false);
assert.equal(validGallery([maps,city,{...image,image:'invalid'}]),false);
assert.equal(validGallery([image,{...city,parentId:'map'}]),false);
entries=changeGallery(entries,{type:'rename',id:'city',name:'Capital'});
entries=changeGallery(entries,{type:'move',id:'map',parentId:'maps'});
entries=changeGallery(entries,{type:'remove',id:'city'});
const book={...emptyBook,gallery:entries,tabOrder:['gallery','binder']};
const imported=JSON.parse(JSON.stringify(book));
assert.ok(isReadableProject(imported));assert.ok(validCloudLibrary({novels:[imported],collections:[]}));
assert.deepEqual(imported.gallery,[maps,{...image,parentId:'maps'}]);
assert.equal(emptyBook.gallery,undefined);
const broken={...book,gallery:[{...maps,parentId:city.id},city]};
assert.equal(isReadableProject(broken),false);
assert.equal(validCloudLibrary({novels:[broken],collections:[]}),false);
const {useKachamak}=await import('../src/lib/kachamak/store.ts');
const {galleryImageRef,projectImageSrc}=await import('../src/lib/kachamak/project-image.ts');
const {cloneWorkspaceTab}=await import('../src/lib/kachamak/clone-workspace-tab.ts');
const store=useKachamak.getState();
useKachamak.setState({novels:[book],activeNovelId:book.id});
const ref=galleryImageRef(image.id);
const noteId=store.addNode('binder',null,'doc','Capital');
store.updateNode('binder',noteId,{image:ref,event:{type:'event',start:1,precision:'year',cardStyle:'image',banner:ref}});
const block={id:'home-map',title:'',text:'',layout:'image',width:'full',image:ref};
assert.ok(store.changeHomepage(book.id,{type:'add',block}));
assert.ok(store.updateNovelSettings(book.id,{cover:{...book.cover,image:ref}}));
const saved=useKachamak.getState().novels[0];
const snapshot=JSON.stringify(saved);
assert.equal(snapshot.split(image.image).length-1,1,'One image payload regardless of the number of placements');
assert.equal(JSON.parse(snapshot).sections.binder.find(n=>n.id===noteId).event.banner,ref);
assert.ok(validCloudLibrary({novels:[JSON.parse(snapshot)],collections:[]}));
assert.throws(()=>store.editGallery(book.id,{type:'remove',id:image.id}),/in use/i);
const renamed=changeGallery(saved.gallery,{type:'rename',id:image.id,name:'Capital map'});
assert.equal(projectImageSrc(renamed,ref),image.image);
assert.equal(isReadableProject({...saved,gallery:[]}),false);
const destination=newNovel('Other book','Synthetic');
const copy=cloneWorkspaceTab(saved,'binder',destination,'codex').novel;
assert.equal(copy.gallery.length,1);
const copyNote=copy.sections.codex[0].children.find(n=>n.title==='Capital');
assert.equal(projectImageSrc(copy.gallery,copyNote.image),image.image);
assert.equal(copyNote.event.banner,copyNote.image);
assert.ok(isReadableProject(copy));
console.log('Gallery passed: folder operations, one shared image across placements, delete protection, clone, backup and cloud validation.');
