import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<!doctype html>').window;
globalThis.window=dom;globalThis.document=dom.document;
const {useKachamak}=await import('../src/lib/kachamak/store.ts');
const {findNodeInNovel}=await import('../src/lib/kachamak/utils.ts');
const {pendingLinkReview,prepareLinkReview,mergeReviewChoice}=await import('../src/lib/kachamak/link-review.ts');
const {backlinks,rebaseChoices,contentText}=await import('../src/lib/kachamak/note-links.ts');
const s=useKachamak.getState();s.createNovel('Review regression','Tester');
const a=s.addNode('codex',null,'folder','People'),b=s.addNode('codex',null,'folder','Myths');
const one=s.addNode('codex',a,'doc','Morrigan'),two=s.addNode('codex',b,'doc','Morrigan');
const gate=s.addNode('codex',null,'doc','Gateway');
s.updateNode('codex',gate,{aliases:['Old Gate']});
const other=s.addNode('research',null,'doc','Morrigan');
s.addNode('planning',null,'doc','Notebook');
s.addNode('research',null,'doc','Gatewayhouse');
const source=s.addNode('timeline',null,'doc','Opening');
const html='<p><strong>Morr</strong>igan met Morrigan at Gateway. Gatewayhouse.</p><p><a href="https://example.com">Morrigan</a> <code>Gateway</code></p>';
s.updateNode('timeline',source,{content:html});
const novel=()=>useKachamak.getState().novels[0],node=()=>findNodeInNovel(novel(),source).node;
let pending=pendingLinkReview(novel(),node());
assert.equal(node().linkChoices.length,0,'Typing never accepts detected links');
const oldText='<p>Morrigan, Old Gate, Notebook, Opening, gateway, Gatewayhouse.</p>';
const crossTab={start:0,end:8,text:'Morrigan',targetId:other};
const oldAlias={start:10,end:18,text:'Old Gate',targetId:gate};
const existing={...node(),content:oldText,linkChoices:[crossTab,oldAlias]};
assert.deepEqual(prepareLinkReview(novel(),existing),{content:oldText,linkChoices:[crossTab,oldAlias],unavailable:0});
assert.deepEqual(pendingLinkReview(novel(),existing).map(m=>[m.text,m.targetId]),[['gateway',gate]]);
assert.throws(()=>mergeReviewChoice(novel(),node(),html,crossTab,other),/targets changed/);
assert.deepEqual(pending.map(m=>m.text),['Morrigan','Morrigan','Gateway']);
assert.deepEqual(pending[0].candidates.map(n=>n.id),[one,two]);
assert.equal(pending[0].targetId,null,'Same title in two Codex folders requires a target');
assert.throws(()=>mergeReviewChoice(novel(),node(),html,pending[0],gate),/targets changed/);
const firstOccurrence=pending[0];
const applyChoice=(match,targetId)=>s.updateNode('timeline',source,{linkChoices:mergeReviewChoice(novel(),node(),html,match,targetId)});
applyChoice(firstOccurrence,two);
assert.equal(node().content,html,'Review preserves the manuscript and its formatting');
assert.equal(backlinks(novel(),two)[0].matches.length,1);
pending=pendingLinkReview(novel(),node());
assert.deepEqual(pending.map(m=>m.text),['Morrigan','Gateway'],'The second occurrence still needs a decision');
assert.throws(()=>mergeReviewChoice(novel(),node(),html,firstOccurrence,one),/targets changed/);
applyChoice(pending[0],one);
pending=pendingLinkReview(novel(),node());
assert.deepEqual(pending.map(m=>m.text),['Gateway']);
applyChoice(pending[0],null);
assert.deepEqual(node().linkChoices.map(choice=>choice.targetId),[two,one,null],'Repeated names can target different Codex notes');
assert.equal(pendingLinkReview(novel(),node()).length,0,'Accepted and ignored occurrences stay resolved within the current pass');
const saved=JSON.parse(JSON.stringify(novel()));assert.deepEqual(saved.sections.timeline[0].linkChoices,node().linkChoices);
// Ordinary edits rebase selected IDs and ignored occurrences, never repoint names.
s.updateNode('timeline',source,{content:'<p>Before.</p>'+html});
assert.equal(pendingLinkReview(novel(),node()).length,0);
s.updateNode('codex',two,{title:'The Other Morrigan'});
assert.equal(node().linkChoices[0].targetId,two);
assert.throws(()=>mergeReviewChoice(novel(),node(),html,firstOccurrence,two),/changed/);
assert.throws(()=>mergeReviewChoice(novel(),node(),node().content,{start:999,end:1000,text:'x'},gate),/changed/);
s.updateNode('codex',two,{title:'Morrigan'});
assert.equal(rebaseChoices('Morrigan','Morrigan!', [{start:0,end:8,text:'Morrigan',targetId:two}])[0].targetId,two);
// A new Save drops old skips, retains valid IDs and discovers appended text.
const scanHtml='<p>Morrigan then Gateway.</p>';
const first=pendingLinkReview(novel(),{...node(),content:scanHtml,linkChoices:[]});
const skipped={start:first[0].start,end:first[0].end,text:first[0].text,targetId:null};
const kept={start:first[1].start,end:first[1].end,text:first[1].text,targetId:gate};
const fresh=prepareLinkReview(novel(),{...node(),content:scanHtml,linkChoices:[skipped,kept]});
assert.equal(fresh.content,scanHtml);assert.deepEqual(fresh.linkChoices,[kept]);
assert.deepEqual(pendingLinkReview(novel(),{...node(),...fresh}).map(m=>m.text),['Morrigan']);
assert.deepEqual(pendingLinkReview(novel(),{...node(),...fresh,content:scanHtml+'<p>Morrigan returned.</p>'}).map(m=>m.text),['Morrigan','Morrigan']);
// More than one broken anchor must not shift/drop valid choices between them.
const broken='<p><a href="#note/old-morrigan"><strong>Morrigan</strong></a> then Gateway and <a href="#note/other-old">Morrigan</a>.</p><p><a href="#note/'+gate+'">Gateway</a> <a href="https://example.com">Morrigan</a></p>';
const visible=contentText(broken),position=visible.indexOf('Gateway');
const between={start:position,end:position+7,text:'Gateway',targetId:gate};
const repaired=prepareLinkReview(novel(),{...node(),content:broken,linkChoices:[between]});
assert.equal(repaired.unavailable,2);assert.ok(repaired.content.includes('<strong>Morrigan</strong>'));
assert.ok(repaired.content.includes('href="#note/'+gate+'"'));assert.ok(repaired.content.includes('href="https://example.com"'));
assert.equal(contentText(repaired.content).slice(repaired.linkChoices[0].start,repaired.linkChoices[0].end),'Gateway');
assert.equal(repaired.linkChoices[0].targetId,gate);
assert.deepEqual(pendingLinkReview(novel(),{...node(),...repaired}).map(m=>m.text),['Morrigan','Morrigan']);
assert.ok(pendingLinkReview(novel(),{...node(),...repaired}).every(m=>m.candidates.length===2),'Repair never silently picks between namesakes');
const stale=prepareLinkReview(novel(),{...node(),content:scanHtml,linkChoices:[{...skipped,targetId:'deleted-note'},kept]});
assert.equal(stale.unavailable,1);assert.deepEqual(stale.linkChoices,[kept]);
// An opt-out belongs to the target note, across documents and Save passes.
s.updateNode('codex',a,{aliases:['Cast'],ignoreAutoLinking:true});
s.updateNode('codex',one,{ignoreAutoLinking:true});
const sample='<p>People, Cast, People. Morrigan at Gateway. <a href="#note/'+a+'">People</a></p>';
const acceptedFolder={start:0,end:6,text:'People',targetId:a};
for (const id of [source,gate]) {
  const document={...findNodeInNovel(novel(),id).node,content:sample,linkChoices:[acceptedFolder]};
  const prepared=prepareLinkReview(novel(),document);
  assert.equal(prepared.unavailable,0);
  assert.equal(prepared.content,sample);
  assert.deepEqual(prepared.linkChoices,[acceptedFolder]);
  const pending=pendingLinkReview(novel(),{...document,...prepared});
  assert.ok(pending.every(hit=>!hit.candidates.some(note=>note.id===a||note.id===one)));
  assert.deepEqual(pending.find(hit=>hit.text==='Morrigan').candidates.map(note=>note.id),[two]);
}
s.updateNode('codex',one,{ignoreAutoLinking:false});
s.updateNode('timeline',source,{content:sample,linkChoices:[acceptedFolder]});
const reloaded=JSON.parse(JSON.stringify(novel()));
const reopened=findNodeInNovel(reloaded,source).node;
assert.deepEqual(pendingLinkReview(reloaded,reopened).map(hit=>hit.text),['Morrigan','Gateway']);
assert.deepEqual(pendingLinkReview(reloaded,reopened)[0].candidates.map(note=>note.id),[one,two]);
const {validCloudLibrary}=await import('../scripts/cloud-library-runtime.mjs');
assert.ok(validCloudLibrary({novels:[reloaded],collections:[]}));
assert.deepEqual(pendingLinkReview(novel(),{...findNodeInNovel(novel(),a).node,content:'<p>Gateway</p>'}).map(hit=>hit.targetId),[gate]);
s.updateNode('codex',a,{ignoreAutoLinking:false});
assert.deepEqual(pendingLinkReview(novel(),node()).map(hit=>hit.text),['Cast','People','Morrigan','Gateway']);
console.log('Link review passed: Codex targets, duplicate titles, preserved alias and cross-tab links, individual decisions, preserved HTML, stable IDs, rebasing, roundtrip and stale-content rejection.');
