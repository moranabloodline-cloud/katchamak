import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<!doctype html>').window;
globalThis.window=dom;globalThis.document=dom.document;
const {useKachamak}=await import('../src/lib/kachamak/store.ts');
const {findNodeInNovel}=await import('../src/lib/kachamak/utils.ts');
const {pendingLinkReview,reviewDecisions,mergeReviewChoices}=await import('../src/lib/kachamak/link-review.ts');
const {backlinks,rebaseChoices}=await import('../src/lib/kachamak/note-links.ts');
const s=useKachamak.getState();s.createNovel('Review regression','Tester');
const a=s.addNode('codex',null,'folder','People'),b=s.addNode('research',null,'folder','Myths');
const one=s.addNode('codex',a,'doc','Morrigan'),two=s.addNode('research',b,'doc','Morrigan');
const gate=s.addNode('planning',null,'doc','Old Gate');s.updateNode('planning',gate,{aliases:['Gateway']});
const source=s.addNode('timeline',null,'doc','Opening');
const html='<p><strong>Morr</strong>igan met Morrigan at Gateway. Gatewayhouse.</p><p><a href="https://example.com">Morrigan</a> <code>Gateway</code></p>';
s.updateNode('timeline',source,{content:html});
const novel=()=>useKachamak.getState().novels[0],node=()=>findNodeInNovel(novel(),source).node;
let pending=pendingLinkReview(novel(),node());
assert.equal(node().linkChoices.length,0,'Typing never accepts detected links');
assert.deepEqual(pending.map(m=>m.text),['Morrigan','Morrigan','Gateway']);
assert.deepEqual(pending[0].candidates.map(n=>n.id),[one,two]);
assert.equal(pending[0].targetId,null,'Same name in two sections requires a target');
assert.equal(reviewDecisions(pending,pending[0],null,'remaining').length,0,'Accept all stops before ambiguous names');
assert.throws(()=>reviewDecisions(pending,pending[0],gate,'one'));
let decisions=reviewDecisions(pending,pending[0],two,'instances');
assert.equal(decisions.length,2);
s.updateNode('timeline',source,{linkChoices:mergeReviewChoices(novel(),node(),html,decisions)});
assert.equal(node().content,html,'Review never rewrites formatting or manuscript text');
assert.equal(backlinks(novel(),two)[0].matches.length,2,'Cross-tab target keeps its exact identity');
pending=pendingLinkReview(novel(),node());assert.deepEqual(pending.map(m=>m.text),['Gateway']);
decisions=reviewDecisions(pending,pending[0],null,'one');
s.updateNode('timeline',source,{linkChoices:mergeReviewChoices(novel(),node(),html,decisions)});
assert.equal(pendingLinkReview(novel(),node()).length,0,'Accepted and ignored occurrences do not return on Save');
const saved=JSON.parse(JSON.stringify(novel()));assert.deepEqual(saved.sections.timeline[0].linkChoices,node().linkChoices);
// Ordinary edits rebase selected IDs and ignored occurrences, never repoint names.
s.updateNode('timeline',source,{content:'<p>Before.</p>'+html});
assert.equal(pendingLinkReview(novel(),node()).length,0);
s.updateNode('research',two,{title:'The Other Morrigan'});
assert.equal(node().linkChoices[0].targetId,two);
assert.throws(()=>mergeReviewChoices(novel(),node(),html,decisions),/changed/);
assert.throws(()=>mergeReviewChoices(novel(),node(),node().content,[{start:999,end:1000,text:'x',targetId:gate}]),/changed/);
// Unique prefix is accepted in order; later ambiguity is still left for the user.
s.updateNode('timeline',source,{content:'<p>Gateway then Morrigan.</p>',linkChoices:[]});
s.updateNode('research',two,{title:'Morrigan'});
pending=pendingLinkReview(novel(),node());
assert.equal(reviewDecisions(pending,pending[0],null,'remaining').length,1);
assert.equal(rebaseChoices('Morrigan','Morrigan!', [{start:0,end:8,text:'Morrigan',targetId:two}])[0].targetId,two);
console.log('Link review passed: every tab, duplicate names, aliases, all/one/ignore decisions, preserved HTML, stable IDs, rebasing, roundtrip and stale-content rejection.');
