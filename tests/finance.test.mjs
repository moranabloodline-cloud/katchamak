import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<html><body></body></html>',{url:'https://test.local'}).window;
Object.defineProperty(globalThis,'window',{configurable:true,value:dom});
Object.defineProperty(globalThis,'document',{configurable:true,value:dom.document});
const {useKachamak,normalizeNovelSections,isUsableBackup}=await import('../src/lib/kachamak/store.ts');
const {findNode}=await import('../src/lib/kachamak/utils.ts');
const {newNovel}=await import('../src/lib/kachamak/seed.ts');
const {workspaceTabs}=await import('../src/lib/kachamak/workspace-tabs.ts');
const {validCloudLibrary}=await import('../scripts/cloud-library-runtime.mjs');
const {manuscriptMarkdown,manuscriptHtml}=await import('../src/lib/kachamak/manuscript-export.ts');
const {decimalAmount,financeOverview,financeScope,parseAmount,sortedTransactions,validTransaction}=await import('../src/lib/kachamak/finance.ts');

const s=useKachamak.getState();
const book=()=>useKachamak.getState().novels.find(n=>n.id===useKachamak.getState().activeNovelId);
const roots=()=>book().sections.finance;
const summary=()=>financeOverview(roots());
s.createNovel('Finance QA','Author');
assert.ok(workspaceTabs(book(),true).find(t=>t.key==='finance'));
const legacy=newNovel('Old project','Author');delete legacy.sections.finance;
normalizeNovelSections(legacy);
assert.deepEqual(legacy.sections.finance,[]);
assert.ok(workspaceTabs(legacy,true).find(t=>t.key==='finance'));
s.setTab('finance');assert.equal(book().financeCurrency,'EUR');
assert.equal(summary().reached,false);assert.equal(summary().progress,0);
const folder=s.addNode('finance',null,'folder','Campaign');
const child=s.addNode('finance',folder,'folder','Ads');
const sales=s.addNode('finance',null,'folder','Sales');
const add=(parent,type,title,amount,date)=>{
  const id=s.addNode('finance',parent,type,title);
  s.updateNode('finance',id,{transaction:{type,amountMinor:parseAmount(amount),date,description:'QA description'}});
  return id;
};
const cost=add(child,'expense','Advertising','1000','2026-10-01');
const income=add(sales,'income','Book sale','650,00','2026-11-21');
const overview=summary();
assert.deepEqual([overview.income,overview.expense,overview.net,overview.remaining,overview.progress,overview.reached],[65000n,100000n,-35000n,35000n,65,false]);
assert.deepEqual(overview.months,[['2026-10',{income:0n,expense:100000n}],['2026-11',{income:65000n,expense:0n}]]);
assert.deepEqual(overview.groups.map(g=>[g.id,g.income,g.expense]),[[folder,0n,100000n],[sales,65000n,0n]]);
assert.equal(financeScope(roots(),cost).id,child);
assert.equal(financeScope(roots(),sales,folder).id,folder);
assert.equal(financeOverview(findNode(roots(),folder).children).entries.length,1);
const ids=(key,asc)=>sortedTransactions(overview.entries,key,asc).map(n=>n.id);
assert.deepEqual(ids('title',true),[cost,income]);assert.deepEqual(ids('date',false),[income,cost]);assert.deepEqual(ids('amount',true),[income,cost]);
assert.equal(s.updateNovelSettings(book().id,{financeCurrency:'RSD'}),true);
assert.equal(summary().remaining,35000n);
const original=findNode(roots(),income).transaction;
s.updateNode('finance',income,{transaction:{...original,amountMinor:100000}});
assert.equal(summary().reached,true);assert.equal(summary().remaining,0n);
s.updateNode('finance',income,{transaction:{...original,type:'expense',date:'2026-12-01'}});
assert.equal(summary().income,0n);assert.equal(summary().expense,165000n);
s.updateNode('finance',income,{transaction:original});
s.moveTreeNotes(book().id,'finance',[{id:cost,parentId:child}],sales);
assert.equal(financeOverview(findNode(roots(),folder).children).expense,0n);
assert.equal(financeOverview(findNode(roots(),sales).children).net,-35000n);
assert.throws(()=>s.moveTreeNotes(book().id,'finance',[{id:cost,parentId:sales}],income));
s.deleteNode('finance',cost);assert.equal(summary().reached,true);assert.equal(summary().expense,0n);
s.restoreFromTrash(book().trash.at(-1).id);assert.equal(summary().expense,100000n);
s.hideTab(book().id,'finance');s.setTab('finance');s.closeTab('finance');s.setTab('finance');
assert.equal(summary().entries.length,2);
const backup=JSON.stringify(book());
assert.equal(validCloudLibrary({novels:[JSON.parse(backup)],collections:[]}),true);
assert.equal(isUsableBackup(JSON.parse(backup)),true);
assert.equal(s.importNovel(backup).ok,true);assert.equal(book().financeCurrency,'RSD');
assert.equal(summary().remaining,35000n);assert.deepEqual(summary().entries.map(n=>n.id).sort(),[cost,income].sort());
assert.match(manuscriptMarkdown(book(),true),/Income · 650\.00 RSD · 2026-11-21\n\nQA description/);
assert.match(manuscriptHtml(book(),true),/Expense · 1000\.00 RSD · 2026-10-01/);
assert.ok(!manuscriptMarkdown(book()).includes('Advertising'));
for(const invalid of ['1.234','-1','1e8','']) assert.equal(parseAmount(invalid),null);
assert.equal(parseAmount('0.29')+parseAmount('0.01'),30);
assert.equal(validTransaction({...original,date:'2026-02-30'}),false);
const high={...findNode(roots(),income),children:[],transaction:{...original,amountMinor:9999999999999}};
const highTotal=financeOverview(Array.from({length:1001},(_,i)=>({...high,id:'big'+i}))).income;
assert.equal(decimalAmount(highTotal),'100099999999989.99');
assert.equal(decimalAmount(-1n),'-0.01');
const broken=JSON.parse(backup);findNode(broken.sections.finance,cost).transaction.amountMinor=-1;
assert.equal(validCloudLibrary({novels:[broken],collections:[]}),false);
assert.equal(s.importNovel(JSON.stringify(broken)).ok,false);
console.log('Finance passed: optional tabs, legacy data, exact cents, totals, break-even, grouped series, subtree moves, editing, sorting, trash/restore, per-book currency, JSON/cloud and Markdown/HTML export.');
