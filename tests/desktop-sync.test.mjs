import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { verifiedSave } from "../scripts/desktop-sync.mjs";
const root = mkdtempSync(path.join(os.tmpdir(), "katchamak-desktop-sync-"));
const git = (cwd, ...args) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
try {
  const remote = path.join(root, "remote.git"), local = path.join(root, "local");
  mkdirSync(remote); git(remote, "init", "--bare", "--initial-branch=main");
  git(root, "clone", remote, local);
  git(local, "config", "user.name", "Test"); git(local, "config", "user.email", "test@example.test");
  mkdirSync(path.join(local, "src"));
  writeFileSync(path.join(local, ".gitignore"), ".desktop-runtime/\nuser-projects/\n");
  writeFileSync(path.join(local, "src/app.txt"), "original");
  git(local, "add", "."); git(local, "commit", "-m", "initial"); git(local, "push", "origin", "main");
  const initial = git(local, "rev-parse", "HEAD");
  writeFileSync(path.join(local, "src/app.txt"), "broken");
  assert.throws(() => verifiedSave(local, { enforceRemote: false, commands: [[process.execPath, "-e", "process.exit(1)"]] }), /Verification failed/);
  assert.equal(git(local, "rev-parse", "HEAD"), initial);
  assert.equal(git(remote, "rev-parse", "main"), initial);
  assert.equal(readFileSync(path.join(local, "src/app.txt"), "utf8"), "broken");
  writeFileSync(path.join(local, "src/app.txt"), "fixed");
  mkdirSync(path.join(local, "user-projects")); writeFileSync(path.join(local, "user-projects/manuscript.json"), "private writing");
  assert.equal(verifiedSave(local, { enforceRemote: false, commands: [] }).status, "pushed");
  assert.equal(git(remote, "rev-parse", "main"), git(local, "rev-parse", "HEAD"));
  assert.equal(git(local, "ls-files", "user-projects"), "");
  const hook = path.join(remote, "hooks/pre-receive");
  writeFileSync(hook, "#!/bin/sh\nexit 1\n", { mode: 0o755 });
  writeFileSync(path.join(local, "src/app.txt"), "verified but offline");
  const pending = verifiedSave(local, { enforceRemote: false, commands: [] });
  assert.equal(pending.status, "push_pending");
  const pendingCommit = git(local, "rev-parse", "HEAD");
  rmSync(hook);
  git(local, "remote", "set-url", "origin", path.join(root, "unavailable.git"));
  assert.throws(() => verifiedSave(local, { enforceRemote: false, commands: [] }));
  assert.equal(JSON.parse(readFileSync(path.join(local, ".desktop-runtime/sync-state.json"))).pendingCommit, pendingCommit);
  git(local, "remote", "set-url", "origin", remote);
  assert.equal(verifiedSave(local, { enforceRemote: false, commands: [] }).status, "pushed");
  assert.equal(git(remote, "rev-parse", "main"), pendingCommit, "pending verified commit is sent after reconnection");
  assert.equal(git(local, "rev-parse", "HEAD"), pendingCommit, "retry never creates a duplicate commit");
  writeFileSync(path.join(local, "src/app.txt"), "first edit");
  const before = git(local, "rev-parse", "HEAD");
  assert.equal(verifiedSave(local, { enforceRemote: false, commands: [[process.execPath, "-e", "require('fs').writeFileSync('src/app.txt','second edit')"]] }).status, "changed_during_checks");
  assert.equal(git(local, "rev-parse", "HEAD"), before);
  writeFileSync(path.join(local, "src/app.txt"), "second edit");
  const other = path.join(root, "other"); git(root, "clone", remote, other); git(other, "config", "user.name", "Other"); git(other, "config", "user.email", "other@example.test");
  writeFileSync(path.join(other, "src/app.txt"), "remote edit"); git(other, "commit", "-am", "remote change"); git(other, "push", "origin", "main");
  assert.throws(() => verifiedSave(local, { enforceRemote: false, commands: [] }), /main changed/);
  assert.equal(readFileSync(path.join(local, "src/app.txt"), "utf8"), "second edit");
  assert.equal(git(local, "branch", "--show-current"), "main");
  console.log("Desktop synchronization: failed checks, edit during checks, remote conflict, private-data exclusion and verified push passed.");
} finally { rmSync(root, { recursive: true, force: true }); }
