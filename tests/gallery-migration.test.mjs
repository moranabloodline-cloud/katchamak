import assert from 'node:assert/strict';
import { migrateBookArtwork, migrateLibraryArtwork } from '../src/lib/kachamak/migrate-gallery-images.ts';
import { projectImageSrc, projectImageRefs } from '../src/lib/kachamak/project-image.ts';
import { newNovel } from '../src/lib/kachamak/seed.ts';
import { validCloudLibrary } from '../src/lib/kachamak/cloud-write-validation.mjs';
import { useKachamak } from '../src/lib/kachamak/store.ts';

const manuscript = newNovel('Atlas', 'QA');
const shared = 'data:image/png;base64,QUJD';
const map = 'data:image/jpeg;base64,REVG';
const cutout = 'data:image/png;base64,R0hJ';
const frame = { ratio: 2, zoom: 2, x: .2, y: .75, fade: false };
const node = (id, image, children = []) => ({ id, title: id, ...(image && { image }), kind: 'doc', content: '<p>Text</p>', children });
const block = { id: 'map', title: 'Old town', layout: 'image', width: 'full', text: '', image: map, imageFrame: frame, imageCutout: cutout };
manuscript.cover.image = shared;
manuscript.gallery = [
  { kind: 'folder', id: 'folder', parentId: null, name: 'Maps' },
  { kind: 'image', id: 'old', parentId: 'folder', name: 'My original name', image: shared },
  { kind: 'image', id: 'second', parentId: null, name: 'Second upload', image: shared }
];
manuscript.sections.binder = [node('root', undefined, [node('leaf', shared)])];
manuscript.sections.timeline = [{ ...node('event', 'gallery:second'), event: { type: 'event', start: 0, precision: 'day', banner: shared } }];
manuscript.homepage = { locked: true, blocks: [block] };
manuscript.homePages = [{ id: 'subpage', parentId: null, title: 'History', locked: true, blocks: [{ ...block, image: shared }] }];
manuscript.trash = [{ id: 'trash-item', section: 'codex', parentId: null, deletedAt: 1, node: node('trash', map) }];
const original = JSON.stringify(manuscript);
const other = newNovel('Other book', 'QA');
other.cover.image = map;
const empty = newNovel('Empty', 'QA');
const library = migrateLibraryArtwork([manuscript, other, empty]);
const [book, second] = library;
assert.equal(JSON.stringify(manuscript), original);
assert.equal(validCloudLibrary({ novels: library, collections: [] }), true);
assert.deepEqual(book.gallery.slice(0, 2), manuscript.gallery.slice(0, 2));
assert.deepEqual(book.gallery.filter(e => e.kind === 'image').map(e => e.image), [shared, map]);
const ref = book.homepage.blocks[0].image;
assert.deepEqual([...projectImageRefs(book)].sort(), [ref, ref, ...Array(5).fill('gallery:old')].sort());
assert.equal(projectImageSrc(book.gallery, ref), map);
assert.deepEqual(book.homepage.blocks[0], { ...block, image: ref });
assert.equal(book.updatedAt, manuscript.updatedAt);
assert.equal(book.sections.binder[0].children[0].content, '<p>Text</p>');
assert.equal(second.gallery.length, 1);
assert.equal(projectImageSrc(second.gallery, second.cover.image), map);
assert.notEqual(second.cover.image, ref);
assert.equal(library[2], empty);
assert.equal(migrateLibraryArtwork(library), library);
assert.deepEqual(migrateBookArtwork(JSON.parse(original)), book);
const occupied = { ...manuscript, gallery: [...manuscript.gallery, { kind: 'folder', id: ref.slice(8), parentId: null, name: 'Existing folder' }] };
const resolved = migrateBookArtwork(occupied);
assert.notEqual(resolved.homepage.blocks[0].image, ref);
assert.equal(projectImageSrc(resolved.gallery, resolved.homepage.blocks[0].image), map);
const reloaded = JSON.parse(JSON.stringify(book));
assert.equal(migrateBookArtwork(reloaded), reloaded);
assert.deepEqual(useKachamak.persist.getOptions().migrate({ novels: [JSON.parse(original)] }, 50).novels, [book]);
assert.ok(useKachamak.getState().importNovel(original).ok);
const imported = useKachamak.getState().novels.at(-1);
assert.equal(imported.gallery.filter(e => e.kind === 'image').length, 2);
assert.equal(projectImageSrc(imported.gallery, imported.cover.image), shared);
const { Window } = await import('happy-dom');
globalThis.document = new Window().document;
const markup = '<p>Before</p><img alt="Map" src="' + map + '"><p>After</p>';
const inline = newNovel('Imported prose', 'QA');
inline.sections.binder = [{ ...node('embedded'), content: markup, synopsis: markup }];
const indexed = migrateBookArtwork(inline);
assert.deepEqual(indexed.sections.binder[0], inline.sections.binder[0]);
assert.equal(indexed.gallery.length, 1);
assert.equal(indexed.gallery[0].image, map);
assert.equal(migrateBookArtwork(indexed), indexed);
useKachamak.setState({novels:[indexed],activeNovelId:indexed.id});
assert.throws(()=>useKachamak.getState().editGallery(indexed.id,{type:'remove',id:indexed.gallery[0].id}),/in use/i);
console.log('Passed migration, nested gallery reuse, placement rendering, crop, cutout, embedded HTML, trash, book isolation, import, refresh and collision checks.');
