import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
globalThis.window = new Window({url:'https://test.local'});
globalThis.document = window.document;
const {useKachamak} = await import('../src/lib/kachamak/store.ts');
const {noteRelationships, familyDeletionImpact} = await import('../src/lib/kachamak/family-tree.ts');
const {validCloudLibrary} = await import('../scripts/cloud-library-runtime.mjs');
const state = useKachamak.getState;
state().createNovel('Family Trash fixture','Tester');
const book = () => state().novels.find(n => n.id === state().activeNovelId);
const add = (section, title, parent = null) => state().addNode(section, parent, 'doc', title);
const [a,b,c,d] = ['A','B','C','D'].map(name => add('codex',name));
const root = add('family','Root');
const branch = add('family','Branch',root);
const other = add('family','Other');
const members = (id,ids) => state().updateNode('family',id,{familyMembers:ids});
members(root,[a,b]); members(branch,[a,c]); members(other,[a,b,d]);
const record = (tree,from,to,kind) => assert.equal(state().changeFamilyRelationship(book().id,tree,{from,to,kind}),null);
record(root,a,b,'mother');
record(branch,a,c,'mother');
record(other,b,d,'guardian');
const prose = '<p>A link in the manuscript.</p>';
state().updateNode('codex',c,{content:prose,linkChoices:[{start:0,end:1,text:'A',targetId:a}]});
const codex = JSON.stringify(book().sections.codex);
const restore = id => state().restoreFromTrash(id);
const remove = id => state().deleteNode('family',id);
const snapshot = JSON.stringify(book());
const impact = familyDeletionImpact(book(),root);
assert.equal(impact.related.length,2);
assert.equal(impact.exclusive.size,1);
assert.ok(noteRelationships(book(),c).some(row => row.target.id===b && row.reason));
remove(root);
assert.deepEqual(book().sections.family.map(n=>n.id),[other]);
assert.deepEqual(book().familyRelationships.map(e=>e.to),[b,d]);
assert.deepEqual(noteRelationships(book(),c),[]);
assert.equal(JSON.stringify(book().sections.codex),codex);
const rootTrash = book().trash[0].id;
const deleted = JSON.parse(JSON.stringify(book()));
assert.ok(validCloudLibrary({novels:[deleted],collections:[]}));
const corrupt = structuredClone(deleted);
corrupt.trash[0].familyRelationships = [{}];
assert.equal(validCloudLibrary({novels:[corrupt],collections:[]}),false);
assert.ok(state().importNovel(JSON.stringify(deleted)).ok);
assert.equal(restore(rootTrash),undefined);
assert.equal(book().sections.family[0].children[0].id,branch);
assert.equal(book().familyRelationships.length,3);
assert.equal(JSON.stringify(book().sections.codex),codex);
assert.ok(noteRelationships(book(),c).some(row=>row.target.id===b && row.reason));
// The original book remains deleted when its imported copy is restored.
assert.deepEqual(state().novels.find(n=>n.id===deleted.id).familyRelationships,deleted.familyRelationships);
remove(root); const first = book().trash[0].id;
remove(other); const second = book().trash[0].id;
assert.deepEqual(book().familyRelationships,[]);
assert.equal(restore(first),undefined);
assert.equal(book().familyRelationships.length,2);
assert.equal(state().changeFamilyRelationship(book().id,root,{from:a,to:b,kind:'mother'},true),null);
assert.equal(restore(second),undefined);
assert.deepEqual(book().familyRelationships.map(e=>e.to).sort(),[c,d].sort());
// A newer conflicting parent link cannot be overwritten or destroy the archived tree.
assert.ok(state().importNovel(snapshot).ok);
remove(root); const archived = book().trash[0].id;
members(other,[a,b,c,d]); record(other,c,a,'mother');
const before = JSON.stringify(book());
assert.match(restore(archived),/loop/);
assert.equal(JSON.stringify(book()),before);
assert.equal(state().changeFamilyRelationship(book().id,other,{from:c,to:a,kind:'mother'},true),null);
assert.equal(restore(archived),undefined);
assert.equal(book().familyRelationships.length,3);
// Removing a tree with a trashed Codex member also removes its recorded links.
state().deleteNode('codex',c);
members(other,[a,b,d]); remove(root);
const codexTrash = book().trash.find(t=>t.section==='codex');
assert.equal(restore(codexTrash.id),undefined);
assert.deepEqual(noteRelationships(book(),c),[]);
state().emptyTrash();
assert.equal(book().familyRelationships.length,2);
// An old Trash item has no snapshot: restore it, then delete under the new rules.
const legacy = structuredClone(deleted);
delete legacy.trash[0].familyRelationships;
legacy.familyRelationships = JSON.parse(snapshot).familyRelationships;
assert.ok(state().importNovel(JSON.stringify(legacy)).ok);
assert.equal(restore(rootTrash),undefined);
remove(root);
assert.deepEqual(noteRelationships(book(),c),[]);
console.log('Passed family deletion, inferred links, shared trees, Codex text, backup, restore order, legacy Trash and ancestry conflicts.');
