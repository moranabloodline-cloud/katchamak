import assert from 'node:assert/strict';
import {useKachamak} from '../src/lib/kachamak/store.ts';
import {findNodeInNovel} from '../src/lib/kachamak/utils.ts';
import {captureNoteLocation,openProjectNote,returnToPreviousNote,useNoteTrail} from '../src/lib/kachamak/note-navigation.ts';
import {createLinkedCodexNote} from '../src/lib/kachamak/create-linked-note.ts';
import {indexNotes,referenceTo} from '../src/lib/kachamak/knowledge.ts';
const state=useKachamak.getState();state.createNovel('Connected notes','Test');
const source=state.addNode('binder',null,'doc','Arrival'),other=state.addNode('binder',null,'doc','Departure');
const parent=state.addNode('codex',null,'doc','People');
state.updateNode('binder',source,{content:'<p><em>Captain Vale</em> arrived.</p><p><br></p>'});
state.openNoteTab(source);state.select(source);state.setView('write');
const project=useKachamak.getState().activeNovelId,location=captureNoteLocation();
const created=createLinkedCodexNote(project,source,'Captain Vale',parent);
assert.ok(created);assert.deepEqual(captureNoteLocation(),location,'Creating a note must keep the writing location and panes');
let novel=useKachamak.getState().novels[0],target=findNodeInNovel(novel,created);
assert.equal(target.section,'codex');assert.equal(target.node.kind,'doc');assert.equal(target.node.content,'');
assert.equal(findNodeInNovel(novel,parent).node.children[0].id,created);
assert.ok(findNodeInNovel(novel,source).node.links.includes(created));
assert.equal(findNodeInNovel(novel,source).node.content,'<p><em>Captain Vale</em> arrived.</p><p><br></p>');
assert.ok(referenceTo(indexNotes(novel).find(n=>n.node.id===source),target.node,novel));
assert.equal(createLinkedCodexNote('wrong-project',source,'Wrong'),null);
assert.equal(createLinkedCodexNote(project,'missing','Wrong'),null);
assert.equal(createLinkedCodexNote(project,source,'  '),null);
assert.equal(createLinkedCodexNote(project,source,'Wrong',other),null);
assert.equal(openProjectNote(created,true),true);
assert.equal(useKachamak.getState().paneAId,source);assert.equal(useKachamak.getState().paneBId,created);
assert.equal(useKachamak.getState().view,'split');assert.equal(useKachamak.getState().activePane,'b');
assert.equal(returnToPreviousNote(),true);assert.deepEqual(captureNoteLocation(),location,'Back restores the folder tab and Write, not just the selected ID');
assert.equal(openProjectNote('missing'),false);assert.equal(useNoteTrail.getState().entries.length,0);
useKachamak.setState({view:'split',paneAId:source,paneBId:other,activePane:'b',selectedNodeId:other,activeTab:'binder'});
const split=captureNoteLocation();openProjectNote(created,true);
assert.equal(useKachamak.getState().paneBId,other);assert.equal(useKachamak.getState().paneAId,created);
returnToPreviousNote();assert.deepEqual(captureNoteLocation(),split,'Both Split panes survive following a reference');
openProjectNote(created);state.deleteNode('binder',other);
assert.equal(returnToPreviousNote(),false,'Deleted source notes are not reopened');
state.select(source);openProjectNote(created);state.closeNovel();
assert.equal(useNoteTrail.getState().entries.length,0,'Reading history never crosses projects/accounts');
console.log('Connected note workflow passed: blank Codex children, manuscript links, unchanged text, invalid targets, folder-tab return, both Split panes, deleted references and project isolation.');
