import assert from 'node:assert/strict';
import {newNovel} from '../src/lib/kachamak/seed.ts';
import {indexNotes,matchName,referenceTo,searchNotes,inlineNoteIds} from '../src/lib/kachamak/knowledge.ts';
import {JSDOM} from 'jsdom';
const dom=new JSDOM().window;globalThis.window=dom;globalThis.document=dom.document;globalThis.DOMParser=dom.DOMParser;
const {manuscriptHtml,manuscriptMarkdown,manuscriptNotes,manuscriptWords}=await import('../src/lib/kachamak/manuscript-export.ts');
const novel=newNovel('Book <One>','Test Author');
const note=(id,title,content='',children=[])=>({id,title,content,children,kind:'doc',synopsis:'',notes:'',label:'',status:'',createdAt:1,updatedAt:1});
const character={...note('character','Morrigan'),aliases:['Morana','The Ferryman']};
novel.sections.codex=[character,note('ann','Ann'),note('unicode','Ćira')];
novel.sections.binder=[note('act','Act One','',[note('chapter','Chapter One','<p>Morana visits Cork.</p>'),note('chapter-2','Chapter Two','<p>Two words.</p>')])];
novel.sections.research=[{...note('research','Cork research','<p>Background facts</p>'),links:['chapter']}];
novel.sections.planning=[note('outline','Outline','<a href="#note/character" data-katchamak-note="character">her</a>')];
const index=indexNotes(novel), chapter=index.find(n=>n.node.id==='chapter');
assert.equal(index.length,8);assert.equal(chapter.path,'binder / Act One');
assert.equal(matchName(chapter.text,character).name,'Morana');
assert.equal(matchName('annex and bannister',novel.sections.codex[1]),null,'Short substrings are not mentions');
assert.equal(matchName('It was ĆIRA.',novel.sections.codex[2]).name,'ĆIRA','Unicode case and word boundaries');
assert.equal(matchName('The Ferryman arrived',character).name,'The Ferryman');
assert.equal(referenceTo(index.find(n=>n.node.id==='research'),chapter.node).explicit,true,'Links work across every section');
assert.equal(referenceTo(index.find(n=>n.node.id==='outline'),character).explicit,true,'Inline note links produce backlinks');
assert.deepEqual(inlineNoteIds('<a href="#note/character">Morrigan</a>'),['character']);
assert.equal(searchNotes(index,'Morana')[0].node.id,'character','Aliases are searchable');
assert.equal(searchNotes(index,'Cork research')[0].node.id,'research','Exact title outranks body content');
assert.ok(!searchNotes(index,'Morana','character').some(n=>n.node.id==='character'));
character.title='A new name';
assert.equal(referenceTo(index.find(n=>n.node.id==='outline'),character).explicit,true,'Renaming never breaks identity links');
const selected=new Set(['chapter','chapter-2']);
assert.deepEqual(manuscriptNotes(novel).map(n=>n.node.id),['act','chapter','chapter-2']);
assert.equal(manuscriptWords(novel,selected),5,'Compile counts body text once, excluding Codex and metadata');
const html=manuscriptHtml(novel,selected);assert.ok(html.includes('Book &lt;One&gt;'));assert.ok(html.indexOf('Chapter One')<html.indexOf('Chapter Two'));assert.ok(!html.includes('Background facts'));
const md=manuscriptMarkdown(novel,selected);assert.ok(md.includes('### Chapter One'));assert.ok(md.includes('Morana visits Cork.'));assert.ok(!md.includes('Cork research'));
const {useKachamak,isUsableBackup}=await import('../src/lib/kachamak/store.ts');
assert.equal(isUsableBackup(novel),true);
const invalid=structuredClone(novel);invalid.sections.codex[0].aliases='not an array';assert.equal(isUsableBackup(invalid),false);
const old=structuredClone(novel);delete old.sections.codex[0].aliases;
useKachamak.persist.setOptions({storage:{getItem:()=>({state:{...useKachamak.getInitialState(),novels:[old]},version:7}),setItem(){},removeItem(){}}});
await useKachamak.persist.rehydrate();
assert.equal(useKachamak.getState().novels[0].sections.binder[0].children[0].content,'<p>Morana visits Cork.</p>');
assert.deepEqual(useKachamak.getState().novels[0].sections.research[0].links,['chapter']);
assert.deepEqual(useKachamak.getState().novels[0].sections.codex[0].aliases,[],'v7 migration preserves notes and adds optional aliases');
console.log('Knowledge and manuscript export passed: Unicode/whole-name mentions, aliases, cross-section links, backlinks, renaming, ranked search, manuscript ordering, own-text totals and v7 migration.');
