import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
globalThis.window=new Window({url:'https://test.local'});
globalThis.document=window.document;
const {useKachamak,exportNovelJson,isUsableBackup}=await import('../src/lib/kachamak/store.ts');
const {familyMembers,familyEdges,familyLayout,validFamilyRelationships}=await import('../src/lib/kachamak/family-tree.ts');
const {validCloudLibrary}=await import('../scripts/cloud-library-runtime.mjs');
const state=useKachamak.getState;
state().createNovel('Synthetic family','QA');
const bookId=state().activeNovelId;
const book=()=>state().novels.find(n=>n.id===bookId);
const add=(section,title,parent=null)=>state().addNode(section,parent,'doc',title);
const folder=add('codex','Cast');
const [ada,bea,cam,dale]=['Ada','Bea','Cam','Dale'].map(name=>add('codex',name,folder));
const one=add('family','Main family'),two=add('family','Another branch',one);
const tree=id=>id===one?book().sections.family[0]:book().sections.family[0].children[0];
const visible=id=>familyEdges(book(),familyMembers(book(),tree(id)));
const members=(id,list)=>state().updateNode('family',id,{familyMembers:list});
const rel=(kind,from,to)=>({kind,from,to});
const change=(id,...args)=>state().changeFamilyRelationship(bookId,id,...args);
const parent=rel('parent',ada,bea),partners=rel('partner',bea,cam),child=rel('parent',bea,dale);
members(one,[ada,bea,cam,dale]);members(two,[bea]);
assert.equal(change(one,parent),null);
assert.deepEqual(visible(two),[]);
members(two,[ada,bea]);
assert.deepEqual(visible(two),[parent]);
assert.equal(change(one,partners),null);assert.equal(change(one,child),null);
assert.equal(change(one,rel('parent',cam,dale)),null);
assert.match(change(one,rel('partner',cam,bea)),/already/);
assert.match(change(one,rel('parent',dale,ada)),/ancestor/);
assert.match(change(two,rel('parent',ada,ada)),/different/);
const people=familyMembers(book(),tree(one)),edges=visible(one);
const {positions}=familyLayout(people,edges);
assert.equal(positions.get(cam).y,positions.get(bea).y);
for(const edge of edges.filter(e=>e.kind==='parent'))assert.ok(positions.get(edge.from).y<positions.get(edge.to).y);
assert.equal(new Set([...positions.values()].map(p=>p.x+','+p.y)).size,people.length);
state().updateNode('codex',ada,{title:'Renamed Ada'});
assert.equal(familyMembers(book(),tree(two))[0].title,'Renamed Ada');
members(two,[bea]);assert.equal(visible(one).length,4);assert.equal(book().sections.codex[0].children.length,4);
members(two,[bea,ada]);
state().deleteNode('codex',ada);assert.deepEqual(visible(two),[]);
state().restoreFromTrash(book().trash[0].id);assert.deepEqual(visible(two),[parent]);
assert.equal(change(two,parent,true),null);assert.ok(!visible(one).includes(parent));
const original=JSON.parse(JSON.stringify(book()));
assert.ok(validCloudLibrary({novels:[original],collections:[]}));
let downloaded;
const makeURL=URL.createObjectURL;
try{
  URL.createObjectURL=blob=>{downloaded=blob;return 'blob:https://test.local/test';};
  exportNovelJson(book());
}finally{URL.createObjectURL=makeURL;}
const backup=await downloaded.text();
assert.ok(state().importNovel(backup).ok);
const imported=state().novels.find(n=>n.id===state().activeNovelId);
assert.notEqual(imported.id,bookId);
assert.deepEqual(imported.familyRelationships,original.familyRelationships);
assert.deepEqual(imported.sections.family,original.sections.family);
assert.ok(change(one,parent));assert.deepEqual(book(),original);
const old=structuredClone(original);delete old.sections.family;delete old.familyRelationships;
assert.ok(isUsableBackup(old));assert.ok(validCloudLibrary({novels:[old],collections:[]}));
const migrated=useKachamak.persist.getOptions().migrate({novels:[structuredClone(old)]},31).novels[0];
assert.deepEqual(migrated,{...old,sections:{...old.sections,family:[]}});
assert.equal(validFamilyRelationships([{kind:'sibling',from:'a',to:'b'}]),false);
assert.equal(validCloudLibrary({novels:[{...original,familyRelationships:[parent,parent]}],collections:[]}),false);
console.log('Family trees passed: shared book relationships, per-tree membership, generations, cycles, Codex rename/trash/restore, isolation, JSON export/import, cloud validation and legacy migration.');
