import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
globalThis.window=new Window({url:'https://test.local'});
globalThis.document=window.document;
const {useKachamak,exportNovelJson,isUsableBackup}=await import('../src/lib/kachamak/store.ts');
const {familyMembers,familyEdges,familyLayout,familyConnections,familyTreeView,validFamilyRelationships}=await import('../src/lib/kachamak/family-tree.ts');
const {kinshipGroups,relationshipKey}=await import('../src/lib/kachamak/kinship.ts');
const {validCloudLibrary}=await import('../scripts/cloud-library-runtime.mjs');
const state=useKachamak.getState;
state().createNovel('Synthetic family','QA');
const bookId=state().activeNovelId;
const book=()=>state().novels.find(n=>n.id===bookId);
const add=(section,title,parent=null)=>state().addNode(section,parent,'doc',title);
const folder=add('codex','Cast');
const [ada,bea,cam,dale]=['Ada','Bea','Cam','Dale'].map(name=>add('codex',name,folder));
const one=add('family','Main family'),two=add('family','Another branch',one);
const tree=id=>id===one?book().sections.family[0]:book().sections.family[0].children[0];
const visible=id=>familyEdges(book(),familyMembers(book(),tree(id)));
const members=(id,list)=>state().updateNode('family',id,{familyMembers:list});
const rel=(kind,from,to)=>({kind,from,to});
const change=(id,...args)=>state().changeFamilyRelationship(bookId,id,...args);
const parent=rel('parent',ada,bea),partners=rel('partner',bea,cam),child=rel('parent',bea,dale);
members(one,[ada,bea,cam,dale]);members(two,[bea]);
assert.equal(change(one,parent),null);
assert.deepEqual(visible(two),[]);
members(two,[ada,bea]);
assert.deepEqual(visible(two),[parent]);
assert.equal(change(one,partners),null);assert.equal(change(one,child),null);
assert.equal(change(one,rel('parent',cam,dale)),null);
assert.match(change(one,rel('partner',cam,bea)),/already/);
assert.match(change(one,rel('parent',dale,ada)),/ancestor/);
assert.match(change(two,rel('parent',ada,ada)),/different/);
const people=familyMembers(book(),tree(one)),edges=visible(one);
const {positions}=familyLayout(people,edges);
assert.equal(positions.get(cam).y,positions.get(bea).y);
for(const edge of edges.filter(e=>e.kind==='parent'))assert.ok(positions.get(edge.from).y<positions.get(edge.to).y);
assert.equal(new Set([...positions.values()].map(p=>p.x+','+p.y)).size,people.length);
state().updateNode('codex',ada,{title:'Renamed Ada'});
assert.equal(familyMembers(book(),tree(two))[0].title,'Renamed Ada');
members(two,[bea]);assert.equal(visible(one).length,4);assert.equal(book().sections.codex[0].children.length,4);
members(two,[bea,ada]);
state().deleteNode('codex',ada);assert.deepEqual(visible(two),[]);
state().restoreFromTrash(book().trash[0].id);assert.deepEqual(visible(two),[parent]);
assert.equal(change(two,parent,true),null);assert.ok(!visible(one).includes(parent));
const sibling=rel('sister',ada,bea);
const custom={...rel('custom',ada,bea),label:'Zakleta sestra',mutual:true};
assert.equal(change(one,sibling),null);assert.ok(visible(two).includes(sibling));
assert.match(change(two,rel('brother',bea,ada)),/already/);
assert.equal(change(two,custom),null);
assert.match(change(two,{...custom,from:bea,to:ada,label:'zakleta sestra'}),/already/);
assert.ok(change(two,{...custom,label:'   '}));
assert.equal(change(one,rel('nephew',bea,ada)),null);
assert.match(change(one,rel('maternal_aunt',ada,bea)),/already/);
const roles=familyConnections(visible(two));
assert.equal(roles.length,1);assert.equal(roles[0].roles.length,3);
assert.equal(change(one,rel('aunt',ada,bea),true),null);
assert.ok(visible(two).includes(custom));assert.equal(visible(two).length,2);
assert.equal(change(two,rel('daughter',bea,ada)),null);
assert.match(change(one,rel('mother',ada,bea)),/already/);
assert.match(change(one,rel('grandfather',dale,ada)),/ancestor/);
assert.match(change(one,rel('adopted_son',ada,dale)),/ancestor/);
const extended=[rel('granddaughter','young','old'),rel('mother','old','mid'),rel('father','mid','young')];
const layout=familyLayout(['young','old','mid'].map(id=>({id})),extended);
assert.ok(layout.positions.get('old').y<layout.positions.get('mid').y);
assert.ok(layout.positions.get('mid').y<layout.positions.get('young').y);
for(const pos of layout.positions.values())assert.ok(pos.y+62<=layout.height);
const branch=familyLayout(['a','b','c'].map(id=>({id})),[rel('niece','b','a'),rel('sister','b','c')]);
assert.ok(branch.positions.get('a').y<branch.positions.get('b').y);
assert.equal(branch.positions.get('b').y,branch.positions.get('c').y);
const crossGeneration=[rel('father','a','b'),rel('son-in-law','a','b')];
assert.ok(validFamilyRelationships(crossGeneration));
const cross=familyLayout(['a','b'].map(id=>({id})),crossGeneration);
assert.ok(cross.positions.get('a').y<cross.positions.get('b').y);
const presets=kinshipGroups.flatMap(g=>g.kinds);
assert.equal(new Set(presets).size,presets.length);
for(const kind of presets)assert.ok(validFamilyRelationships([rel(kind,'a','b')]),kind);
assert.notEqual(relationshipKey(rel('aunt','a','b')),relationshipKey(rel('aunt','b','a')));
assert.ok(validFamilyRelationships([rel('guardian','a','b'),rel('mother','b','a')]));
for(const patch of [{label:''},{label:'x'.repeat(101)},{label:'line\nbreak'},{label:'Role',mutual:'yes'}])
  assert.equal(validFamilyRelationships([{...custom,...patch}]),false);
const original=JSON.parse(JSON.stringify(book()));
assert.ok(validCloudLibrary({novels:[original],collections:[]}));
let downloaded;
const makeURL=URL.createObjectURL;
try{
  URL.createObjectURL=blob=>{downloaded=blob;return 'blob:https://test.local/test';};
  exportNovelJson(book());
}finally{URL.createObjectURL=makeURL;}
const backup=await downloaded.text();
assert.ok(state().importNovel(backup).ok);
const imported=state().novels.find(n=>n.id===state().activeNovelId);
assert.notEqual(imported.id,bookId);
assert.deepEqual(imported.familyRelationships,original.familyRelationships);
assert.deepEqual(imported.sections.family,original.sections.family);
assert.ok(change(one,parent));assert.deepEqual(book(),original);
const old=structuredClone(original);delete old.sections.family;delete old.familyRelationships;
assert.ok(isUsableBackup(old));assert.ok(validCloudLibrary({novels:[old],collections:[]}));
const migrated=useKachamak.persist.getOptions().migrate({novels:[structuredClone(old)]},31).novels[0];
assert.deepEqual(migrated,{...old,sections:{...old.sections,family:[]}});
assert.deepEqual(useKachamak.persist.getOptions().migrate({novels:[structuredClone(original)]},32).novels[0],original);
assert.equal(validFamilyRelationships([{kind:'unknown-role',from:'a',to:'b'}]),false);
assert.equal(validCloudLibrary({novels:[{...original,familyRelationships:[parent,parent]}],collections:[]}),false);
// Parents and intermediate relatives may live outside the currently open tree.
const lineage=[rel('mother','m','a'),rel('son','b','m'),rel('father','g','m')];
const lineageBook={...original,sections:{...original.sections,codex:['m','a','b','g','p','x'].map(id=>({id,title:id,children:[]}))},familyRelationships:lineage};
const lineageTree={familyMembers:['a','b','g']};
const projection=(records=lineage,source=lineageBook,tree=lineageTree)=>familyTreeView({...source,familyRelationships:records},tree);
const inferred=(records,source,tree)=>[...projection(records,source,tree).reasons.keys()];
const before=JSON.stringify(lineageBook);
assert.deepEqual(inferred(),[rel('brother','b','a'),rel('grandfather','g','a'),rel('grandfather','g','b')]);
assert.deepEqual([...projection().reasons.values()],['Shared parent · m','Through · m','Through · m']);
assert.equal(JSON.stringify(lineageBook),before);
assert.deepEqual(inferred(lineage,JSON.parse(before)),inferred());
assert.deepEqual(inferred(lineage,lineageBook,{familyMembers:['a','b']}),[rel('brother','b','a')]);
assert.deepEqual(inferred([],lineageBook),[]);
assert.deepEqual(inferred(lineage.slice(1)),[rel('grandfather','g','b')]);
assert.deepEqual(inferred(lineage,{...lineageBook,sections:{codex:lineageBook.sections.codex.filter(n=>n.id!=='m')}}),[]);
const neutral=[rel('mother','m','a'),rel('biological_child','b','m')];
const secondParent=[...neutral,rel('parent','p','b'),rel('parent','p','a'),rel('biological_parent','m','a')];
assert.equal(inferred(secondParent).length,1);
assert.equal(inferred(secondParent)[0].kind,'sibling');
assert.deepEqual([...projection(secondParent).reasons.values()],['Shared parents · m, p']);
assert.equal(inferred([rel('adopted_daughter','a','m'),rel('child','b','m')])[0].kind,'sister');
assert.equal(inferred([...lineage,rel('daughter','b','p')]).find(e=>e.kind==='sibling')?.kind,'sibling');
assert.deepEqual(inferred([...lineage,rel('half-sister','a','b'),rel('granddaughter','a','g')]),[rel('grandfather','g','b')]);
assert.equal(projection([...lineage,{...rel('custom','a','b'),label:'Clan kin'}]).reasons.size,3);
const twoRoutes=[rel('parent','g','m'),rel('parent','g','p'),rel('parent','m','a'),rel('parent','p','a')];
assert.deepEqual(inferred(twoRoutes),[rel('grandparent','g','a')]);
assert.deepEqual([...projection(twoRoutes).reasons.values()],['Through · m, p']);
assert.deepEqual(inferred([rel('parent','g','m'),rel('daughter','a','m')]),[rel('granddaughter','a','g')]);
for(const kind of ['guardian','partner','stepparent','foster_parent','godparent','ancestor','grandparent']){
  assert.deepEqual(inferred([rel(kind,'m','a'),rel('parent','m','b')]),[]);
}
